"""
台灣 國小二年級 數學：幾時幾分（108課綱 N-2-13）
  python3 tools/gen_tw_math_g2_telling_time.py
鐘面の長針（5 分ずつ）、幾時幾分の報讀、5 分刻み以外も（長針の小さい目盛り）、長針の位置から分を、整時から整時までの時間（幾小時）、上午・下午の生活場面。
誤答：短針が次の數字に近いとき時を一つ進めてしまう、長針の數字をそのまま分にする（4 → 4 分）、時間で引き算を逆にする。
"""
import random
from tw_common import mcq, lesson, example, make_unit, pick_unique, clock, Names
from tw_g7 import tidy_sets

R = random.Random(81314)
NM = Names(R)


def t(h, m):
    return "%d 時 %d 分" % (h, m) if m else "%d 時" % h


def s1(seen):
    def mk():
        k = R.randint(1, 11)
        q = "長針指著 %d，是幾分？" % k
        return mcq(q, "%d 分" % (5 * k), ["%d 分" % x for x in (k, 5 * k + 5, 10 * k if 10 * k < 60 else 5 * k - 5) if x != 5 * k], "長針從 12 開始，每一個數字是 5 分：%d × 5 ＝ %d 分。" % (k, 5 * k))
    return pick_unique(R, mk, 11, seen) + [mcq("長針指著 12，是幾分？", "0 分（整點）", ["12 分", "60 分", "1 分"], "長針指著 12 是整點，0 分。"),
                                          mcq("長針走一圈是幾分鐘？", "60 分鐘", ["12 分鐘", "100 分鐘", "30 分鐘"], "長針走一圈是 60 分鐘，也就是 1 小時。"),
                                          mcq("短針從 3 走到 4，是過了多久？", "1 小時", ["1 分鐘", "5 分鐘", "4 小時"], "短針走一大格是 1 小時。"),
                                          mcq("長針從 12 走到 6，是過了多久？", "30 分鐘", ["6 分鐘", "60 分鐘", "15 分鐘"], "6 × 5 ＝ 30 分鐘。"),
                                          mcq("長針從 12 走到 3，是過了多久？", "15 分鐘", ["3 分鐘", "30 分鐘", "45 分鐘"], "3 × 5 ＝ 15 分鐘。"),
                                          mcq("1 小時是幾分鐘？", "60 分鐘", ["100 分鐘", "12 分鐘", "24 分鐘"], "1 小時 ＝ 60 分鐘。"),
                                          mcq("長針指著 9，是幾分？", "45 分", ["9 分", "40 分", "50 分"], "9 × 5 ＝ 45 分。"),
                                          mcq("短針指在 7 和 8 中間，長針指著 6，是幾時幾分？", "7 時 30 分", ["8 時 30 分", "6 時 35 分", "7 時 6 分"], "短針還沒到 8，是 7 時；長針 6 是 30 分。"),
                                          mcq("時鐘上的短針叫什麼？", "時針", ["分針", "秒針", "長針"], "短針是時針，長針是分針。")]


def s2(seen):
    def mk():
        h = R.randint(1, 12)
        m = 5 * R.randint(1, 11)
        q = "鐘面上是幾時幾分？" + clock(h, m, 170)
        w = [t(h % 12 + 1, m), "%d 時 %d 分" % (h, m // 5), t(m // 5 if m // 5 else 12, h * 5 % 60) if h * 5 % 60 != m else t(h, (m + 5) % 60 or 5)]
        return mcq(q, t(h, m), w, "短針過了 %d、還沒到 %d，是 %d 時；長針指著 %d，%d × 5 ＝ %d 分。" % (h, h % 12 + 1, h, m // 5, m // 5, m))
    return pick_unique(R, mk, 20, seen)


def s3(seen):
    def mk():
        h = R.randint(1, 12)
        m = R.randint(1, 59)
        if m % 5 == 0:
            return None
        q = "鐘面上是幾時幾分？（數長針走過的小格）" + clock(h, m, 190)
        w = [t(h, m + 1 if m < 59 else m - 1), t(h % 12 + 1, m) if m >= 40 else t(h, m - 1), t(h, m // 5 * 5)]
        return mcq(q, t(h, m), w, "長針過了 %d（%d 分），再數 %d 小格：%d 分；短針在 %d 和 %d 之間，是 %d 時。" % (m // 5 if m // 5 else 12, m // 5 * 5, m % 5, m, h, h % 12 + 1, h))
    return pick_unique(R, mk, 20, seen)


def s4(seen):
    def mk():
        a = R.randint(6, 10)
        d = R.randint(1, 5)
        b = a + d
        ev = R.choice([("上午 %d 時出發去動物園，下午 %d 時回到家", "pm"), ("上午 %d 時到圖書館看書，上午 %d 時離開", "am"), ("上午 %d 時開始烤蛋糕，%s %d 時烤好", "mix")])
        if ev[1] == "am" and b > 12:
            return None
        if ev[1] == "pm":
            b2 = b - 12 if b > 12 else b
            if b <= 12:
                return None
            q = "%s。一共是幾小時？" % (ev[0] % (a, b2))
        elif ev[1] == "am":
            if b >= 12:
                return None
            q = "%s。一共是幾小時？" % (ev[0] % (a, b))
        else:
            if b > 12:
                return None
            q = "上午 %d 時開始烤蛋糕，%s %d 時烤好。一共烤了幾小時？" % (a, "中午" if b == 12 else "上午", b)
        return mcq(q, "%d 小時" % d, ["%d 小時" % x for x in (d + 1, a + d if a + d != d else d + 2, (b - 12 if b > 12 else b) - a if (b > 12 and b - 12 - a > 0) else d + 3) if x != d] + ["%d 小時" % (d + 4)], "從 %d 時數到 %d 時，%d 小時。" % (a, b, d) if b <= 12 else "上午 %d 時到中午 12 時是 %d 小時，12 時到下午 %d 時是 %d 小時，一共 %d 小時。" % (a, 12 - a, b - 12, b - 12, d))
    return pick_unique(R, mk, 20, seen)


def s5(seen):
    def mk():
        h = R.randint(1, 9)
        k = R.choice([1, 2, 3])
        m = 5 * R.randint(0, 11)
        if h + k > 12:
            return None
        q = "現在是 %s，再過 %d 小時是幾時幾分？" % (t(h, m), k)
        return mcq(q, t(h + k, m), [t(h + k + 1, m), t(h, m + 5 * k if m + 5 * k < 60 else m), t(h + k, (m + 30) % 60)], "過了 %d 小時，時增加 %d，分不變：%s。" % (k, k, t(h + k, m)))
    return pick_unique(R, mk, 20, seen)


def main():
    seen = set()
    sets = [("長針和短針", s1(seen)), ("幾時幾分（5 分）", s2(seen)), ("幾時幾分（1 分）", s3(seen)),
            ("經過幾小時", s4(seen)), ("再過幾小時", s5(seen))]
    tidy_sets(sets)
    body = lesson(
        ["短針（時針）告訴我們幾時：短針<b>過了哪個數字</b>就是幾時。",
         "長針（分針）告訴我們幾分：每一個數字是 <b>5 分</b>，每一小格是 1 分。長針走一圈是 60 分鐘 ＝ 1 小時。" + clock(4, 25, 160),
         "上圖：短針過了 4，長針指著 5（25 分），是 4 時 25 分。"],
        [example("短針在 8 和 9 中間，長針指 10", ["8 時；10 × 5 ＝ 50 分。"], "8 時 50 分"),
         example("上午 9 時到上午 11 時", ["9、10、11，經過 2 小時。"], "2 小時")],
        [("8 時 50 分看成 9 時 50 分", "短針還沒到 9，是 8 時"),
         ("長針指 4 讀成 4 分", "每個數字 5 分：20 分"),
         ("上午 10 時到下午 2 時是 8 小時", "10 到 12 是 2 小時，再到 2 時又 2 小時：4 小時")])
    faq = [{"q": "二年級要會看到幾分？",
            "a": "108課綱 N-2-13：以鐘面時針與分針的位置認識「幾時幾分」，並能算兩個整時之間經過幾小時。"},
           {"q": "孩子常把時讀錯怎麼辦？",
            "a": "提醒「短針過了哪個數字」，快到下一個數字（例如 8 時 55 分）時最容易讀錯，可以多練這種時刻。"},
           {"q": "怎麼練 5 分 5 分數？",
            "a": "先背 5 的乘法：5、10、15 …… 60，對照鐘面上的 1 到 12。"}]
    make_unit(R, "grade-2", "telling-time", "N-2-13",
              "鐘面的時刻：以操作活動為主。以鐘面時針與分針之位置認識「幾時幾分」。含兩整時時刻之間的整時點數（時間加減）。",
              "看時鐘：幾時幾分",
              "二年級數學 幾時幾分 練習題｜看時鐘・經過幾小時 學習單（附解答）",
              "幾時幾分",
              "國小二年級數學「看時鐘：幾時幾分」免費學習單：長針和短針、5 分 5 分數、數小格讀幾分、經過幾小時、再過幾小時是幾時。100題線上練習，鐘面圖多，附可列印解答。",
              "長針一個數字 5 分，一小格 1 分",
              "短針過了哪個數字就是幾時。",
              body, faq, sets, 14)


if __name__ == "__main__":
    main()
