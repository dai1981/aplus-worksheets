def lon(x):
    return "0°" if x == 0 else ("%d°E" % x if x > 0 else "%d°W" % -x)


def lat(x):
    return "0°" if x == 0 else ("%d°N" % x if x > 0 else "%d°S" % -x)


def hm(m):
    m %= 24 * 60
    return "%d:%02d" % (m // 60, m % 60)


def f_earth(R):
    k = R.choice(["lt", "bj", "noon", "noon2", "zone", "diff"])
    if k == "lt":
        a, b = R.sample([0, 30, 60, 90, 120, 150, -30, -60, -90, -120, 45, 75, 105], 2)
        h = R.choice([8, 10, 12, 14, 16])
        t = h * 60 + (b - a) * 4
        return it("%s 的地方时为 %d:00 时，%s 的地方时是几点？" % (lon(a), h, lon(b)), hm(t), [hm(h * 60 - (b - a) * 4), hm(t + 60), hm(h * 60 + (b - a) * 2)], "经度每差 1°，地方时差 4 分钟，东早西晚。")
    if k == "bj":
        b = R.choice([90, 105, 135, 75, 60, 0])
        h = R.choice([8, 12, 14, 20])
        t = h * 60 + (b - 120) * 4
        return it("北京时间是 %d:00 时，%s 的地方时是几点？" % (h, lon(b)), hm(t), [hm(h * 60 - (b - 120) * 4), hm(h * 60), hm(t + 60)], "北京时间是 120°E 的地方时，向东加、向西减，每度 4 分钟。")
    if k == "noon":
        p = R.choice([10, 20, 23, 30, 35, 40, 45, 50])
        d, nm = R.choice([(0, "春分日"), (23.4, "夏至日"), (-23.4, "冬至日")])
        h = 90 - abs(p - d)
        return nq("%s，%s 的正午太阳高度是多少度？" % (nm, lat(p)), round(h, 1), [round(90 - abs(p + d), 1), round(90 - p, 1) if d else 90, round(p + abs(d), 1)], "°",
                  "H = 90° − |φ − δ|，%s太阳直射 %s。" % (nm, "赤道" if d == 0 else ("北回归线" if d > 0 else "南回归线")))
    if k == "noon2":
        h = R.choice([50, 60, 66.6, 70, 80])
        return nq("春分日某地（北半球）正午太阳高度为 %s°，该地的纬度是多少？（只写度数）" % num(h), round(90 - h, 1), [h, round(90 - h + 23.4, 1), round(h - 23.4, 1)], "°", "春分日 H = 90° − φ。")
    if k == "zone":
        x, nm = R.choice([(120, "东八区"), (135, "东九区"), (0, "中时区"), (-75, "西五区"), (75, "东五区"), (30, "东二区"), (-120, "西八区"), (150, "东十区"), (105, "东七区"), (90, "东六区")])
        pool = ["东八区", "东九区", "中时区", "西五区", "东五区", "东二区", "西八区", "东十区", "东七区", "东六区", "东一区", "西一区"]
        w = [z for z in pool if z != nm]
        R.shuffle(w)
        return it("%s 位于哪个时区？" % lon(x), nm, w[:3], "时区数 = 经度 ÷ 15，四舍五入；东经在东时区，西经在西时区。")
    CN = "零一二三四五六七八九十"
    a, b = R.choice([(8, 0), (8, -5), (9, 8), (8, 1), (8, -8), (10, 8), (8, 3), (9, -5), (8, -4)])
    d = a - b
    nb = ("东%s区" % CN[b]) if b > 0 else ("中时区" if b == 0 else "西%s区" % CN[-b])
    return nq("东%s区比%s早几个小时？" % (CN[a], nb), d, [d + 1, d - 1, abs(a + b) if abs(a + b) != d else d + 2], "小时", "相差的时区数就是相差的小时数，东早西晚。")


