def f_kin(R):
    k = R.choice(["v", "x", "a", "avg", "stop", "fall", "fallv"])
    if k == "v":
        v0, a, t = R.choice([0, 2, 4, 5, 10]), R.choice([1, 2, 3, 4]), R.choice([2, 3, 4, 5, 6])
        v = v0 + a * t
        return nq("物体以 %d m/s 的初速度做匀加速直线运动，加速度为 %d m/s²，%d s 末的速度是多少？" % (v0, a, t), v, [a * t, v0 + a, v0 * t + a, v + a], "m/s", "v = v₀ + at = %d + %d × %d = %d m/s。" % (v0, a, t, v))
    if k == "x":
        v0, a, t = R.choice([0, 2, 4, 6]), R.choice([2, 4, 6]), R.choice([2, 3, 4, 5])
        x = v0 * t + a * t * t / 2
        return nq("物体以 %d m/s 的初速度做匀加速直线运动，加速度为 %d m/s²，前 %d s 内的位移是多少？" % (v0, a, t), x, [v0 * t + a * t * t, v0 * t + a * t / 2, a * t * t / 2 if v0 else a * t * t], "m",
                  "x = v₀t + ½at² = %d × %d + ½ × %d × %d² = %s m。" % (v0, t, a, t, num(x)))
    if k == "a":
        v0, v, t = R.choice([0, 2, 5]), R.choice([10, 20, 30]), R.choice([2, 4, 5, 10])
        a = (v - v0) / t
        return nq("汽车在 %d s 内速度由 %d m/s 均匀增加到 %d m/s，加速度是多少？" % (t, v0, v), a, [v / t, (v + v0) / t, v - v0, (v - v0) * t], "m/s²", "a = (v − v₀)/t = (%d − %d) ÷ %d = %s m/s²。" % (v, v0, t, num(a)))
    if k == "avg":
        x1, t1, x2, t2 = R.choice([60, 100, 120]), R.choice([2, 4, 5]), R.choice([40, 60, 80]), R.choice([3, 5, 6])
        v = (x1 + x2) / (t1 + t2)
        return nq("物体前 %d s 内通过 %d m，后 %d s 内通过 %d m，全程的平均速度是多少？" % (t1, x1, t2, x2), v, [(x1 / t1 + x2 / t2) / 2, x1 / t1, x2 / t2], "m/s", "平均速度 = 总位移 ÷ 总时间 = %d ÷ %d = %s m/s。" % (x1 + x2, t1 + t2, num(v)))
    if k == "stop":
        v0, a = R.choice([10, 15, 20, 30]), R.choice([2, 4, 5])
        t = v0 / a
        T = R.choice([int(t) + 2, int(t) + 4])
        x = v0 * v0 / (2 * a)
        return nq("汽车以 %d m/s 的速度行驶，刹车时加速度大小为 %d m/s²，刹车后 %d s 内的位移是多少？" % (v0, a, T), x, [v0 * T - a * T * T / 2, v0 * T, v0 * t], "m",
                  "汽车 %s s 就停下了，位移 x = v₀² ÷ 2a = %s m。" % (num(t), num(x)))
    if k == "fall":
        t = R.choice([1, 2, 3, 4, 5])
        return nq("物体从高处由静止自由下落，%d s 内下落的高度是多少？（g 取 10 m/s²）" % t, 5 * t * t, [10 * t * t, 10 * t, 5 * t], "m", "h = ½gt² = ½ × 10 × %d² = %d m。" % (t, 5 * t * t))
    h = R.choice([5, 20, 45, 80, 125])
    t = (h / 5) ** 0.5
    return nq("物体从 %d m 高处由静止自由下落，落地时的速度是多少？（g 取 10 m/s²）" % h, 10 * t, [5 * t, t, 2 * h], "m/s", "落地时间 t = √(2h/g) = %s s，v = gt = %s m/s。" % (num(t), num(10 * t)))


def f_force(R):
    k = R.choice(["fma", "a", "fric", "spring", "res", "slope", "lift"])
    if k == "fma":
        m, a = R.choice([2, 4, 5, 10, 50]), R.choice([2, 3, 4, 5])
        return nq("质量为 %d kg 的物体获得 %d m/s² 的加速度，它受到的合力是多少？" % (m, a), m * a, [m / a, m + a, m * a * 10], "N", "F = ma = %d × %d = %d N。" % (m, a, m * a))
    if k == "a":
        F, f, m = R.choice([20, 30, 50]), R.choice([5, 10]), R.choice([5, 10])
        a = (F - f) / m
        return nq("质量 %d kg 的木箱在水平拉力 %d N 作用下运动，受到的摩擦力为 %d N，加速度是多少？" % (m, F, f), a, [F / m, (F + f) / m, F - f], "m/s²", "合力 %d − %d = %d N，a = %d ÷ %d = %s m/s²。" % (F, f, F - f, F - f, m, num(a)))
    if k == "fric":
        m, mu = R.choice([2, 5, 10, 20]), R.choice([0.1, 0.2, 0.25, 0.5])
        f = mu * m * 10
        return nq("质量 %d kg 的物体在水平面上滑动，动摩擦因数为 %s，滑动摩擦力是多少？（g 取 10 m/s²）" % (m, num(mu)), f, [mu * m, m * 10, f * 2], "N", "f = μN = μmg = %s × %d × 10 = %s N。" % (num(mu), m, num(f)))
    if k == "spring":
        kk, x = R.choice([100, 200, 500]), R.choice([2, 4, 5, 10])
        return nq("劲度系数为 %d N/m 的弹簧伸长 %d cm，弹力是多少？" % (kk, x), kk * x / 100, [kk * x, kk / x, kk * x / 10], "N", "F = kx = %d × %s = %s N（先把 cm 换成 m）。" % (kk, num(x / 100), num(kk * x / 100)))
    if k == "res":
        a, b = R.choice([(3, 4), (6, 8), (5, 12), (9, 12)])
        c = (a * a + b * b) ** 0.5
        return nq("大小为 %d N 和 %d N 的两个力互相垂直，它们的合力是多少？" % (a, b), c, [a + b, b - a, (a + b) / 2], "N", "F = √(%d² + %d²) = %s N。" % (a, b, num(c)))
    if k == "slope":
        m = R.choice([2, 4, 5, 10])
        return nq("质量 %d kg 的物体静止在倾角为 30° 的斜面上，它受到的静摩擦力是多少？（g 取 10 m/s²）" % m, m * 5, [m * 10, m * 10 * 0.866, m * 2.5], "N", "静摩擦力等于重力沿斜面的分力 mg sin 30° = %d N。" % (m * 5))
    m, a = R.choice([50, 60]), R.choice([1, 2])
    up = R.choice([True, False])
    N = m * (10 + a) if up else m * (10 - a)
    return nq("质量 %d kg 的人站在电梯里，电梯以 %d m/s² 的加速度%s，人对地板的压力是多少？（g 取 10 m/s²）" % (m, a, "加速上升" if up else "加速下降"), N, [m * 10, m * (10 - a) if up else m * (10 + a), m * a], "N",
              "%s：N − mg = ma 的方向取向上为正，N = %d N。" % ("超重" if up else "失重", N))


def f_curve(R):
    k = R.choice(["t", "x", "ac", "F", "T", "v"])
    if k == "t":
        h = R.choice([5, 20, 45, 80])
        return nq("物体从 %d m 高处水平抛出，经过多长时间落地？（g 取 10 m/s²）" % h, (h / 5) ** 0.5, [h / 10, h / 5, (h / 10) ** 0.5], "s", "竖直方向自由落体：t = √(2h/g) = %s s。" % num((h / 5) ** 0.5))
    if k == "x":
        h, v = R.choice([5, 20, 45, 80]), R.choice([5, 10, 15, 20])
        t = (h / 5) ** 0.5
        return nq("物体从 %d m 高处以 %d m/s 的速度水平抛出，水平位移是多少？（g 取 10 m/s²）" % (h, v), v * t, [v * h / 10, v * t * 2, v], "m", "t = %s s，x = v₀t = %s m。" % (num(t), num(v * t)))
    if k == "ac":
        v, r = R.choice([2, 4, 5, 10]), R.choice([1, 2, 4, 5])
        return nq("物体以 %d m/s 的速度沿半径为 %d m 的圆周做匀速圆周运动，向心加速度是多少？" % (v, r), v * v / r, [v / r, v * r, v * v * r], "m/s²", "a = v²/r = %d² ÷ %d = %s m/s²。" % (v, r, num(v * v / r)))
    if k == "F":
        m, v, r = R.choice([1, 2, 5]), R.choice([2, 4, 6]), R.choice([1, 2, 4])
        return nq("质量 %d kg 的小球以 %d m/s 的速度在半径 %d m 的水平圆周上做匀速圆周运动，所需向心力是多少？" % (m, v, r), m * v * v / r, [m * v / r, m * v * v, m * v * v * r], "N", "F = mv²/r = %s N。" % num(m * v * v / r))
    if k == "T":
        n = R.choice([2, 4, 5, 10])
        return nq("转盘每秒转 %d 圈，它的周期是多少？" % n, 1 / n, [n, 2 * n, 1 / (2 * n)], "s", "T = 1/n = %s s。" % num(1 / n))
    w, r = R.choice([2, 4, 5, 10]), R.choice([0.1, 0.2, 0.5, 2])
    return nq("圆盘转动的角速度为 %d rad/s，离转轴 %s m 处的点线速度是多少？" % (w, num(r)), w * r, [w / r, w * r * r, w * w * r], "m/s", "v = ωr = %s m/s。" % num(w * r))


def f_energy(R):
    k = R.choice(["W", "P", "Ek", "Ep", "fall", "slide", "Pv"])
    if k == "W":
        F, s = R.choice([10, 20, 50]), R.choice([2, 5, 10])
        ang = R.choice([0, 60])
        W = F * s * (1 if ang == 0 else 0.5)
        return nq("用 %d N 的力拉物体，力与位移方向夹角为 %d°，物体移动 %d m，拉力做功多少？" % (F, ang, s), W, [F * s * 2 if ang else F * s / 2, F + s, F * s * 0.866], "J", "W = Fl cos α = %s J。" % num(W))
    if k == "P":
        W, t = R.choice([600, 1200, 3000]), R.choice([10, 20, 60])
        return nq("机器在 %d s 内做功 %d J，功率是多少？" % (t, W), W / t, [W * t, t / W, W / t / 2], "W", "P = W/t = %s W。" % num(W / t))
    if k == "Ek":
        m, v = R.choice([2, 4, 1000]), R.choice([2, 4, 10, 20])
        return nq("质量 %d kg 的物体以 %d m/s 的速度运动，动能是多少？" % (m, v), m * v * v / 2, [m * v * v, m * v / 2, m * v], "J", "Eₖ = ½mv² = %s J。" % num(m * v * v / 2))
    if k == "Ep":
        m, h = R.choice([2, 5, 50]), R.choice([3, 10, 20])
        return nq("质量 %d kg 的物体被举高 %d m，重力势能增加多少？（g 取 10 m/s²）" % (m, h), m * 10 * h, [m * h, m * 10 * h / 2, m * 9.8], "J", "ΔEₚ = mgh = %d J。" % (m * 10 * h))
    if k == "fall":
        h = R.choice([5, 20, 45, 80])
        return nq("不计空气阻力，物体从 %d m 高处由静止下落，落地时的速度是多少？（用机械能守恒，g 取 10 m/s²）" % h, (20 * h) ** 0.5, [10 * h, (10 * h) ** 0.5, 2 * h], "m/s", "mgh = ½mv²，v = √(2gh) = %s m/s。" % num((20 * h) ** 0.5))
    if k == "slide":
        h = R.choice([0.8, 1.25, 1.8, 3.2, 5])
        return nq("小球从高 %s m 的光滑曲面顶端由静止滑下，到达底端的速度是多少？（g 取 10 m/s²）" % num(h), (20 * h) ** 0.5, [10 * h, 20 * h, (10 * h) ** 0.5], "m/s", "光滑曲面只有重力做功，v = √(2gh) = %s m/s。" % num((20 * h) ** 0.5))
    P, v = R.choice([60000, 80000, 90000]), R.choice([20, 30])
    return nq("汽车发动机功率为 %d W，以 %d m/s 匀速行驶，牵引力是多少？" % (P, v), P / v, [P * v, P / v / 2, P / 10], "N", "P = Fv，F = P/v = %s N。" % num(P / v))


def f_grav(R):
    k = R.choice(["ratio", "r2", "v", "gs", "kep", "vr", "wr", "gh"])
    if k == "ratio":
        n = R.choice([2, 3, 4, 5, 6])
        return it_("两个物体之间的距离变为原来的 %d 倍，万有引力变为原来的几分之几？" % n, "1/%d" % (n * n), ["1/%d" % n, "%d 倍" % n, "%d 倍" % (n * n)], "F = GMm/r²，与距离的平方成反比。")
    if k == "r2":
        n = R.choice([2, 3, 4, 5])
        return it_("两个物体的质量都变为原来的 %d 倍，距离不变，万有引力变为原来的几倍？" % n, "%d 倍" % (n * n), ["%d 倍" % n, "%d 倍" % (2 * n), "1/%d" % (n * n)], "F 与两个质量的乘积成正比。")
    if k == "v":
        a, b = R.choice([("第一宇宙速度", "7.9 km/s"), ("第二宇宙速度", "11.2 km/s"), ("第三宇宙速度", "16.7 km/s")])
        return it_("%s是多少？" % a, b, [x for x in ["7.9 km/s", "11.2 km/s", "16.7 km/s", "340 m/s"] if x != b], "第一宇宙速度 7.9 km/s，第二 11.2 km/s，第三 16.7 km/s。")
    if k == "gs":
        n = R.choice([2, 3, 4, 5])
        return it_("卫星轨道半径变为原来的 %d 倍，它受到地球的引力变为原来的多少？" % n, "1/%d" % (n * n), ["1/%d" % n, "%d 倍" % n, "不变"], "引力与轨道半径的平方成反比。")
    if k == "kep":
        n, t = R.choice([(4, 8), (9, 27), (16, 64), (25, 125)])
        return it_("两颗行星绕同一恒星运动，甲的轨道半长轴是乙的 %d 倍，甲的公转周期是乙的几倍？" % n, "%d 倍" % t, ["%d 倍" % n, "%d 倍" % (n * n), "%d 倍" % int(n ** 0.5)], "开普勒第三定律 a³/T² = k，T ∝ a^1.5。")
    if k == "vr":
        n = R.choice([4, 9, 16, 25])
        r = int(n ** 0.5)
        return it_("卫星甲的轨道半径是卫星乙的 %d 倍，甲的线速度是乙的多少？" % n, "1/%d" % r, ["1/%d" % n, "%d 倍" % r, "%d 倍" % n], "GMm/r² = mv²/r，v = √(GM/r)，v ∝ 1/√r。")
    if k == "wr":
        n, t = R.choice([(4, 8), (9, 27), (16, 64)])
        return it_("卫星甲的轨道半径是卫星乙的 %d 倍，甲的运行周期是乙的几倍？" % n, "%d 倍" % t, ["%d 倍" % n, "1/%d" % t, "%d 倍" % (n * n)], "T = 2π√(r³/GM)，T ∝ r^1.5。")
    n = R.choice([2, 3, 4])
    return it_("距地面高度等于地球半径的 %d 倍处，重力加速度约为地面的多少？" % (n - 1), "1/%d" % (n * n), ["1/%d" % ((n - 1) ** 2) if n > 2 else "1/2", "1/%d" % n, "不变"],
               "到地心的距离是 %dR，g ∝ 1/r²。" % n)


