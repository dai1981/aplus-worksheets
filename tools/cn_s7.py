def chain7(R):
    C = [("草 → 鼠 → 蛇 → 鹰", "鼠", "蛇"), ("草 → 蝗虫 → 青蛙 → 蛇", "蝗虫", "青蛙"), ("水藻 → 虾 → 小鱼 → 大鱼", "虾", "小鱼"), ("草 → 兔 → 狐", "兔", "狐"),
         ("植物 → 昆虫 → 食虫鸟 → 鹰", "昆虫", "食虫鸟"), ("树 → 蝉 → 螳螂 → 黄雀", "蝉", "螳螂"), ("浮游植物 → 浮游动物 → 鱼 → 海鸥", "浮游动物", "鱼")]
    c, a, b = R.choice(C)
    p = c.split(" → ")
    k = R.choice(["prod", "top", "toxic", "less", "count"])
    if k == "prod":
        return it("食物链“%s”中，生产者是谁？" % c, p[0], R.sample(p[1:], 2) + ["阳光"], "生产者是能进行光合作用的%s。" % p[0])
    if k == "top":
        return it("食物链“%s”中，体内有毒物质积累最多的是谁？" % c, p[-1], [p[0], p[1], "阳光"], "有毒物质沿食物链逐级积累，最高营养级最多。")
    if k == "toxic":
        return it("食物链“%s”中，%s以谁为食？" % (c, b), a, [p[0], p[-1], "阳光"] if b != p[-1] else [p[0], "阳光", "细菌"], "箭头从被吃者指向吃者。")
    if k == "less":
        return it("食物链“%s”中，如果%s大量减少，短时间内%s的数量会怎样？" % (c, b, a), "增加", ["减少", "不变", "全部消失"], "天敌减少，%s数量增加。" % a)
    return it("食物链“%s”中，一共有几种消费者？" % c, "%d 种" % (len(p) - 1), ["%d 种" % len(p), "%d 种" % (len(p) - 2), "%d 种" % (len(p) + 1)], "除生产者%s外都是消费者。" % p[0])


def scope_calc(R):
    k = R.choice(["mul", "move", "obj"])
    if k == "mul":
        e = R.choice([5, 10, 15, 16])
        o = R.choice([4, 10, 40, 100])
        return it("显微镜目镜 %d×、物镜 %d×，物像放大多少倍？" % (e, o), "%d 倍" % (e * o), ["%d 倍" % (e + o), "%d 倍" % o, "%d 倍" % (e * o * 2)], "%d × %d = %d。" % (e, o, e * o))
    if k == "move":
        d = R.choice(["左上方", "右上方", "左下方", "右下方", "左方", "右方", "上方", "下方"])
        ws = [x for x in ["左上方", "右上方", "左下方", "右下方", "左方", "右方", "上方", "下方"] if x != d]
        return it("视野中物像位于%s，要把它移到视野中央，玻片应向哪里移动？" % d, d, R.sample(ws, 3), "显微镜成倒像，物像偏哪边，玻片就往哪边移。")
    a, b = R.sample([(5, 10), (10, 10), (10, 40), (16, 40), (5, 40), (10, 4), (16, 10)], 2)
    big = a if a[0] * a[1] > b[0] * b[1] else b
    if a[0] * a[1] == b[0] * b[1]:
        return None
    small = b if big is a else a
    f = lambda x: "目镜 %d×、物镜 %d×" % x
    return it("下面两组镜头中，“%s”和“%s”哪组看到的细胞数目更多？" % (f(a), f(b)), f(small), [f(big), "一样多", "都看不到"], "放大倍数越小，看到的细胞越多、越小。")


def latlon(R):
    k = R.choice(["ns", "ew", "hemi", "zone"])
    if k == "ns":
        v = R.choice([5, 10, 20, 30, 40, 50, 60, 70])
        d = R.choice(["N", "S"])
        t = "北纬" if d == "N" else "南纬"
        return it("%d°%s 读作什么？" % (v, d), "%s %d°" % (t, v), ["%s %d°" % ("南纬" if d == "N" else "北纬", v), "东经 %d°" % v, "西经 %d°" % v], "N 表示北纬，S 表示南纬。")
    if k == "ew":
        v = R.choice([20, 40, 60, 80, 100, 120, 140, 160])
        d = R.choice(["E", "W"])
        t = "东经" if d == "E" else "西经"
        return it("%d°%s 读作什么？" % (v, d), "%s %d°" % (t, v), ["%s %d°" % ("西经" if d == "E" else "东经", v), "北纬 %d°" % (v // 2), "南纬 %d°" % (v // 2)], "E 表示东经，W 表示西经。")
    if k == "hemi":
        v = R.choice([10, 30, 50, 80, 100, 120, 150, 170])
        d = R.choice(["E", "W"])
        east = (d == "E" and v < 160) or (d == "W" and v < 20)
        if v in (20, 160):
            return None
        ans = "东半球" if east else "西半球"
        return it("%d°%s 的经线位于东半球还是西半球？" % (v, d), ans, ["东半球" if not east else "西半球", "南半球", "北半球"], "东西半球以 20°W 和 160°E 为界。")
    v = R.choice([10, 20, 30, 40, 50, 60, 70, 80])
    z = "低纬度" if v < 30 else ("中纬度" if v < 60 else "高纬度")
    return it("纬度 %d° 的地方属于低、中、高哪个纬度地区？" % v, z, [x for x in ["低纬度", "中纬度", "高纬度", "零纬度"] if x != z], "0°～30° 低纬度，30°～60° 中纬度，60°～90° 高纬度。")


def scale(R):
    k = R.choice(["d", "map"])
    s = R.choice([10000, 50000, 100000, 200000, 500000, 1000000, 5000000])
    if k == "d":
        cm = R.randint(2, 9)
        km = cm * s / 100000
        f = lambda x: ("%g 千米" % x)
        return it("比例尺 1∶%d，图上 %d 厘米表示实地多少千米？" % (s, cm), f(km), [f(km * 10), f(km / 10), f(km * 100)], "%d × %d 厘米 = %g 千米。" % (cm, s, km))
    km = R.choice([5, 10, 20, 50, 100])
    cm = km * 100000 / s
    if cm != int(cm) or cm > 50 or cm < 1:
        return None
    return it("比例尺 1∶%d，实地距离 %d 千米，图上距离是多少厘米？" % (s, km), "%d 厘米" % cm, ["%d 厘米" % (cm * 10), "%g 厘米" % (cm / 10), "%d 厘米" % (cm + 1)], "%d 千米 = %d 厘米，再除以 %d。" % (km, km * 100000, s))


def temp_alt(R):
    k = R.choice(["top", "diff", "range"])
    if k == "top":
        t = R.randint(14, 30)
        h = R.choice([500, 1000, 1500, 2000, 2500, 3000])
        top = t - h * 0.006
        f = lambda x: ("%g ℃" % round(x, 1)).replace("-", "−")
        return it("山脚气温 %d ℃，山顶比山脚高 %d 米，山顶气温约多少？" % (t, h), f(top), [f(t + h * 0.006), f(t - h * 0.06), f(t - h * 0.0006)], "海拔每升高 100 米约降 0.6 ℃：%d − %g = %g。" % (t, h * 0.006, top))
    if k == "diff":
        a = R.randint(20, 34)
        b = a - R.randint(5, 14)
        return it("某地一天最高气温 %d ℃，最低气温 %d ℃，气温日较差是多少？" % (a, b), "%d ℃" % (a - b), ["%d ℃" % (a + b), "%d ℃" % a, "%d ℃" % ((a + b) // 2)], "%d − %d = %d。" % (a, b, a - b))
    xs = [R.randint(2, 30) for _ in range(4)]
    if sum(xs) % 4:
        return None
    m = sum(xs) // 4
    return it("某日 2 时、8 时、14 时、20 时的气温分别是 %s ℃、%s ℃、%s ℃、%s ℃，日平均气温是多少？" % tuple(str(x).replace("-", "−") for x in xs), "%d ℃" % m, ["%d ℃" % sum(xs), "%d ℃" % max(xs), "%d ℃" % (m + 2)] if m + 2 != max(xs) else ["%d ℃" % sum(xs), "%d ℃" % (m + 3), "%d ℃" % (m - 2)],
              "(%d + %d + %d + %d) ÷ 4 = %d。" % (xs[0], xs[1], xs[2], xs[3], m))
