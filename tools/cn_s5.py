    if k == "count":
        n = R.choice([20, 24, 30, 36, 40, 45, 48, 50, 60])
        t = R.choice([15, 30])
        c = n * 60 // t if (n * 60) % t == 0 else None
        if not c:
            return None
        return it("一个摆 %d 秒摆了 %d 次，照这样计算，1 分钟大约摆多少次？" % (t, n), "%d 次" % c, ["%d 次" % n, "%d 次" % (n + t), "%d 次" % (c * 2)],
                  "1 分 = 60 秒，%d × (60 ÷ %d) = %d（次）。" % (n, t, c))
    if k == "adj":
        a, b = R.sample(range(20, 60, 2), 2)
        if a == b:
            return None
        if a < b:
            return it("一个摆 1 分钟摆 %d 次，要让它 1 分钟摆 %d 次，应怎样调整？" % (a, b), "缩短摆长", ["增加摆长", "换更重的摆锤", "增大摆动幅度"], "摆长越短，摆得越快。")
