def wind(R):
    dirs = ["北", "南", "东", "西", "东北", "西北", "东南", "西南"]
    opp = {"北": "南", "南": "北", "东": "西", "西": "东", "东北": "西南", "西南": "东北", "西北": "东南", "东南": "西北"}
