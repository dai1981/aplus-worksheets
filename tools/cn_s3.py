def speed(R):
    k = R.choice(["v", "v2", "d", "t"])
    if k == "v":
        v = R.randint(2, 9)
        t = R.randint(5, 20)
        d = v * t
        thing = R.choice(["小车", "自行车", "小狗", "小明"])
        return it("%s %d 秒行驶了 %d 米，它的速度是多少？" % (thing, t, d), "%d 米/秒" % v, ["%d 米/秒" % (d * t), "%d 米/秒" % (d + t), "%d 米/秒" % (v + 1)],
                  "速度 = 距离 ÷ 时间 = %d ÷ %d = %d（米/秒）。" % (d, t, v))
    if k == "v2":
        v = R.choice([40, 50, 60, 80, 90, 100, 120])
        t = R.randint(2, 5)
        thing = R.choice(["汽车", "大巴车", "火车"])
        return it("%s %d 小时行驶了 %d 千米，平均每小时行驶多少千米？" % (thing, t, v * t), "%d 千米" % v, ["%d 千米" % (v * t), "%d 千米" % (v + t), "%d 千米" % (v // 2)],
                  "%d ÷ %d = %d（千米）。" % (v * t, t, v))
    if k == "d":
        v = R.randint(2, 8)
        t = R.randint(6, 15)
        return it("一只小狗每秒跑 %d 米，%d 秒能跑多少米？" % (v, t), "%d 米" % (v * t), ["%d 米" % (v + t), "%d 米" % (v * t + v), "%d 米" % (t)], "%d × %d = %d（米）。" % (v, t, v * t))
    v = R.randint(3, 9)
    t = R.randint(4, 12)
    return it("一辆玩具车每秒行驶 %d 米，行驶 %d 米要用多少秒？" % (v, v * t), "%d 秒" % t, ["%d 秒" % (v * t * v), "%d 秒" % (t + v), "%d 秒" % (t + 1)], "%d ÷ %d = %d（秒）。" % (v * t, v, t))


