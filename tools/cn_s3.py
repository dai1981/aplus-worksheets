def spring(R):
    k = R.choice(["read", "hook", "range"])
    if k == "read":
        n = R.randint(1, 9)
        half = R.choice([0, 5])
        v = "%d.%d N" % (n, half) if half else "%d N" % n
        val = n + half / 10
        alt = ["%d N" % (n + 1), "%d N" % (n * 10), "%.1f N" % (val + 0.5) if half else "%d.5 N" % n]
        return it("弹簧测力计每一大格是 1 N，每一小格是 0.5 N。指针停在第 %d 大格%s处，读数是多少？" % (n, "后的第 1 小格" if half else "", ), v,
                  alt, "读数是 %s。" % v)
    if k == "hook":
        each = R.choice([0.5, 1, 2])
        m = R.randint(2, 6)
        tot = each * m
        f = lambda x: ("%g N" % x)
        return it("挂 1 个钩码时测力计读数是 %s，挂 %d 个同样的钩码时读数是多少？" % (f(each), m), f(tot), [f(each), f(tot + each), f(m)], "%g × %d = %g（N）。" % (each, m, tot))
    q = R.choice([5, 10])
    v = R.choice([q + 2, q + 5, q * 2])
    return it("一个弹簧测力计的量程是 0～%d N，能不能用它测量约 %d N 的力？" % (q, v), "不能，超过了量程", ["能，越大越准", "能，但要用两只手", "只能测一半"],
              "测量的力不能超过量程，否则会损坏弹簧。")
