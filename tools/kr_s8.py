def f_wave(R):
    k = R.choice(["v", "f", "T", "echo"])
    if k == "v":
        f, lam = R.choice([(2, 3), (5, 2), (10, 0.5), (4, 1.5), (20, 0.2), (340, 1)])
        return nq("진동수가 %s Hz, 파장이 %s m인 파동의 속력은 몇 m/s일까요?" % (num(f), num(lam)), f * lam, [f / lam, lam / f, f + lam], "m/s", "파동의 속력 = 진동수 × 파장 = %s × %s = %s m/s입니다." % (num(f), num(lam), num(f * lam)))
    if k == "f":
        T = R.choice([0.5, 0.2, 0.1, 2, 4, 0.25])
        return nq("주기가 %s초인 파동의 진동수는 몇 Hz일까요?" % num(T), 1 / T, [T, T * 2, 1 / T * 2], "Hz", "진동수 = 1 ÷ 주기 = 1 ÷ %s = %s Hz입니다." % (num(T), num(1 / T)))
    if k == "T":
        n, t = R.choice([(10, 5), (20, 4), (30, 10), (50, 10), (12, 6)])
        return nq("물결이 %d초 동안 %d번 진동했습니다. 이 물결의 진동수는 몇 Hz일까요?" % (t, n), n / t, [t / n, n * t, n], "Hz", "진동수 = 진동 횟수 ÷ 시간 = %d ÷ %d = %s Hz입니다." % (n, t, num(n / t)))
    t = R.choice([2, 3, 4, 6, 1])
    return nq("절벽을 향해 소리를 질렀더니 %d초 뒤에 메아리가 들렸습니다. 절벽까지의 거리는 몇 m일까요? (소리의 속력: 340 m/s)" % t, 340 * t / 2, [340 * t, 340 / t, 170 / t], "m",
              "소리가 갔다가 돌아오는 데 %d초가 걸렸으므로 거리 = 340 × %d ÷ 2 = %s m입니다." % (t, t, num(340 * t / 2)))


