def f_eco(R):
    k = R.choice(["mark", "eff", "need", "K2", "plot", "lam"])
    if k == "mark":
        M, n, m = R.choice([(50, 40, 10), (100, 60, 15), (30, 50, 5), (80, 100, 20), (60, 45, 9), (40, 30, 6)])
        N = M * n / m
        return nq("用标记重捕法调查某种鼠，第一次捕获并标记 %d 只，第二次捕获 %d 只，其中有标记的 %d 只，该种群数量约为多少只？" % (M, n, m), N, [M + n, M * m / n, n * m], "只", "N = M × n ÷ m = %s 只。" % num(N))
    if k == "eff":
        a, b = R.choice([(1000, 150), (5000, 600), (2000, 300), (800, 120), (10000, 1500)])
        return nq("某营养级同化的能量为 %d kJ，下一营养级同化了 %d kJ，能量传递效率是多少？" % (a, b), b / a * 100, [a / b, b / a * 10, (a - b) / a * 100], "%", "传递效率 = %d ÷ %d × 100%% = %s%%。" % (b, a, num(b / a * 100)))
    if k == "need":
        n, e = R.choice([(1, 10), (2, 10), (2, 20), (3, 10), (1, 20)])
        lv = R.choice([3, 4])
        need = n / (e / 100) ** (lv - 1)
        return nq("在“植物 → …”的食物链中，第 %d 营养级的生物要增加 %d kg，按 %d%% 的传递效率计算，至少需要消耗植物多少千克？" % (lv, n, e), need if e == 20 else None, [n * e, n / (e / 100), n * 5 ** (lv - 2)], "kg",
                  "“至少”用最大传递效率 20%%：%d ÷ 20%%^%d = %s kg。" % (n, lv - 1, num(need))) if e == 20 else \
            nq("在“植物 → …”的食物链中，第 %d 营养级的生物要增加 %d kg，按 10%% 的传递效率计算，需要消耗植物多少千克？" % (lv, n), n * 10 ** (lv - 1), [n * 10, n * 5 ** (lv - 1), n * 10 ** lv], "kg",
               "每升高一个营养级需要 10 倍：%d × 10^%d = %s kg。" % (n, lv - 1, num(n * 10 ** (lv - 1))))
    if k == "K2":
        K = R.choice([200, 400, 600, 1000, 1500])
        return nq("某鱼塘中鱼的环境容纳量 K 值为 %d 条，为获得最大持续产量，捕捞后应使鱼的数量维持在多少条左右？" % K, K / 2, [K, K / 4, K * 3 / 4], "条", "K/2 时种群增长速率最大。")
    if k == "plot":
        a, s = R.choice([(12, 1), (30, 2), (45, 5), (60, 4), (25, 1)])
        return nq("用样方法调查某草地上蒲公英的密度，5 个 %d m² 的样方中共有 %d 株，种群密度约为多少？" % (s, a), a / (5 * s), [a / 5, a / s, a * s / 5], "株/m²", "密度 = 总株数 ÷ 总面积 = %s 株/m²。" % num(a / (5 * s)))
    N0, lam, t = R.choice([(100, 2, 3), (50, 3, 2), (20, 2, 5), (10, 3, 3)])
    return nq("某种群初始数量为 %d，每年是上一年的 %d 倍（“J”形增长），%d 年后种群数量是多少？" % (N0, lam, t), N0 * lam ** t, [N0 * lam * t, N0 + lam * t, N0 * lam ** (t - 1)], "", "Nₜ = N₀λᵗ = %d × %d^%d。" % (N0, lam, t))


