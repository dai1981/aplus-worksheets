def f_mr(R):
    rows = [r for r in FORM if r[1]]
    f, d, name = R.choice(rows)
    k = R.choice(["mr", "frac", "ratio"])
    m = mr(d)
    if k == "mr":
        return nq("%s（%s）的相对分子质量是多少？（H-1 C-12 N-14 O-16 Na-23 Mg-24 Al-27 S-32 Cl-35.5 Ca-40 Fe-56 Cu-64 Zn-65）" % (name, F(f)), m,
                  [sum(AR[x] for x in d), m + 16, m - AR[list(d)[0]], m * 2], "", "把各原子的相对原子质量乘以原子个数再相加：%s。" % num(m))
    if k == "frac":
        el = R.choice(list(d))
        p = AR[el] * d[el] / m * 100
        if abs(p - round(p, 1)) > 1e-6:
            return None
        return nq("%s（%s）中 %s 元素的质量分数是多少？（相对原子质量见课本）" % (name, F(f), el), p, [AR[el] / m * 100, 100 - p, d[el] / sum(d.values()) * 100], "%",
                  "%s × %d ÷ %s × 100%% = %s%%。" % (num(AR[el]), d[el], num(m), num(p)))
    els = list(d)
    if len(els) != 2:
        return None
    a, b = els
    x, y = AR[a] * d[a], AR[b] * d[b]
    from math import gcd
    if x != int(x) or y != int(y):
        return None
    g = gcd(int(x), int(y))
    ans = "%d∶%d" % (x / g, y / g)
    return it("%s（%s）中 %s、%s 两种元素的质量比是多少？" % (name, F(f), a, b), ans, ["%d∶%d" % (d[a], d[b]), "%d∶%d" % (y / g, x / g), "%d∶%d" % (AR[a], AR[b])],
              "%s∶%s = (%s × %d)∶(%s × %d) = %s。" % (a, b, num(AR[a]), d[a], num(AR[b]), d[b], ans))


