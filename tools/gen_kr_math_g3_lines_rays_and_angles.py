def points_segments():
    n = R.choice([3, 4, 5])
    pts = {3: [(60, 40), (200, 40), (130, 150)], 4: [(50, 40), (210, 40), (210, 160), (50, 160)],
           5: [(130, 20), (220, 85), (185, 175), (75, 175), (40, 85)]}[n]
    labs = R.sample(PT, n)
    body = "".join(dot(x, y, 5) + lab(x + (14 if x > 130 else -14), y - 12, t) for (x, y), t in zip(pts, labs))
    ans = n * (n - 1) // 2
    q = fig(svg_wrap(260, 200, body, "점 %d개" % n)) + "점 %d개 중 두 점을 이어 그을 수 있는 선분은 모두 몇 개인가요?" % n
    return mcq(q, "%d개" % ans, ["%d개" % x for x in (n, n - 1, ans + 1, n * (n - 1)) if x != ans],
               "한 점에서 다른 점으로 %d개씩 그을 수 있지만, 선분 ㄱㄴ과 선분 ㄴㄱ은 같은 선분이에요. %d × %d ÷ 2 = <b>%d</b>(개)" % (n - 1, n, n - 1, ans))


