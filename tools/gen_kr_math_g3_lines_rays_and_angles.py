def angle_fig(a, b, c, deg=None):
    deg = deg or R.choice([40, 60, 75, 90, 110, 130])
    vx, vy = (50 if deg <= 90 else 150), 165
    r = 150
    x1, y1 = vx + r, vy
    t = math.radians(deg)
    x2, y2 = vx + r * math.cos(t), vy - r * math.sin(t)
    s = arrow(vx, vy, x1, y1) + arrow(vx, vy, x2, y2) + dot(vx, vy) + dot(vx + 110, vy) + dot(vx + 110 * math.cos(t), vy - 110 * math.sin(t))
    s += lab(vx - 14, vy + 10, b) + lab(vx + 110, vy + 22, a) + lab(vx + 110 * math.cos(t) - 16, vy - 110 * math.sin(t) - 10, c)
    if deg == 90:
        s += "<polyline points='%d,%d %d,%d %d,%d' fill='none' stroke='%s' stroke-width='2'/>" % (vx + 16, vy, vx + 16, vy - 16, vx, vy - 16, RED)
    return fig(svg_wrap(320, 200, s, "각"))


def angle_parts():
    a, b, c = R.sample(PT[:8], 3)
    k = R.choice(["vertex", "name", "side"])
