def f_mol(R):
    k = R.choice(["n", "m", "N", "V", "Vm", "c", "cm", "dil"])
    f, M, name = R.choice(MM)
    if k == "n":
        n = R.choice([0.1, 0.2, 0.5, 1, 2, 3])
        m = n * M
        return nq("%s g %s（%s）的物质的量是多少？（摩尔质量 %s g/mol）" % (num(m), name, f, num(M)), n, [m * M, M / m, n * 2], "mol", "n = m/M = %s ÷ %s = %s mol。" % (num(m), num(M), num(n)))
    if k == "m":
        n = R.choice([0.1, 0.25, 0.5, 2, 3])
        return nq("%s mol %s（%s）的质量是多少？（摩尔质量 %s g/mol）" % (num(n), name, f, num(M)), n * M, [M / n, M, n * M / 2], "g", "m = nM = %s × %s = %s g。" % (num(n), num(M), num(n * M)))
    if k == "N":
        f, M, name = R.choice(GAS + [("H₂O", 18, "水")])
        n = R.choice([0.5, 1, 2, 3, 5])
        return nq("%s mol %s 中约含有多少个分子？（Nᴀ 取 6.02×10²³ mol⁻¹）" % (num(n), name), n * 6.02e23, [6.02e23 / n, n * 6.02e23 * 2, n * 6.02e22], "", "N = n·Nᴀ = %s × 6.02×10²³。" % num(n))
    if k == "V":
        f, M, name = R.choice(GAS)
        n = R.choice([0.1, 0.2, 0.5, 1, 2, 3])
        return nq("标准状况下，%s mol %s 的体积是多少？" % (num(n), name), n * 22.4, [n * 22.4 * 2, 22.4 / n, n * M], "L", "V = n·Vₘ = %s × 22.4 L/mol = %s L。" % (num(n), num(n * 22.4)))
    if k == "Vm":
        f, M, name = R.choice(GAS)
        V = R.choice([2.24, 4.48, 11.2, 22.4, 33.6, 44.8])
        n = V / 22.4
        return nq("标准状况下，%s L %s 的质量是多少？（摩尔质量 %s g/mol）" % (num(V), name, num(M)), n * M, [V * M, M / n, n * 22.4], "g", "n = %s ÷ 22.4 = %s mol，m = %s g。" % (num(V), num(n), num(n * M)))
    if k == "c":
        n, V = R.choice([0.1, 0.2, 0.5, 1, 2]), R.choice([0.1, 0.25, 0.5, 1, 2])
        return nq("把 %s mol %s 溶于水配成 %s L 溶液，物质的量浓度是多少？" % (num(n), name, num(V)), n / V, [n * V, V / n, n], "mol/L", "c = n/V = %s mol/L。" % num(n / V))
    if k == "cm":
        c, V = R.choice([0.1, 0.2, 0.5, 1, 2]), R.choice([0.1, 0.25, 0.5, 1])
        f, M, name = R.choice([("NaCl", 58.5, "氯化钠"), ("NaOH", 40, "氢氧化钠"), ("Na₂CO₃", 106, "碳酸钠")])
        return nq("配制 %s L %s mol/L 的%s溶液，需要%s多少克？（摩尔质量 %s g/mol）" % (num(V), num(c), name, name, num(M)), c * V * M, [c * M, c * V, c / V * M], "g", "m = cVM = %s g。" % num(c * V * M))
    c1, V1, c2 = R.choice([2, 5, 10, 18]), R.choice([10, 20, 50, 100]), R.choice([0.5, 1, 2])
    if c2 >= c1:
        return None
    return nq("把 %d mL %d mol/L 的溶液稀释到 %s mol/L，稀释后溶液的体积是多少？" % (V1, c1, num(c2)), c1 * V1 / c2, [c2 * V1 / c1, c1 * V1 / c2 - V1, V1 * c1], "mL", "稀释前后溶质的物质的量不变：c₁V₁ = c₂V₂。")


def f_period(R):
    E = [("H", 1), ("Li", 3), ("C", 6), ("N", 7), ("O", 8), ("F", 9), ("Na", 11), ("Mg", 12), ("Al", 13), ("Si", 14), ("P", 15), ("S", 16), ("Cl", 17), ("Ar", 18), ("K", 19), ("Ca", 20)]
    s, z = R.choice(E)
    shells = [2, 8, 8, 2]
    out, left = [], z
    for c in shells:
        if left <= 0:
            break
        out.append(min(c, left))
        left -= min(c, left)
    per = len(out)
    last = out[-1]
    k = R.choice(["per", "grp", "e", "last"])
    if k == "per":
        return nq("原子序数为 %d 的元素 %s 位于第几周期？" % (z, s), per, [per + 1, last, per - 1 if per > 1 else per + 2, z], "", "核外有 %d 个电子层，位于第 %d 周期。" % (per, per))
    if k == "grp":
        if s in ("H", "Ar"):
            return None
        names = {1: "ⅠA", 2: "ⅡA", 3: "ⅢA", 4: "ⅣA", 5: "ⅤA", 6: "ⅥA", 7: "ⅦA"}
        if last not in names:
            return None
        return it("原子序数为 %d 的元素 %s 位于第几族？" % (z, s), "第 %s 族" % names[last], ["第 %s 族" % names[x] for x in sorted(names) if x != last][:3] if last > 3 else ["第 %s 族" % names[x] for x in (5, 6, 7)],
                  "最外层有 %d 个电子，主族序数等于最外层电子数。" % last)
    if k == "e":
        return nq("%s 原子核外有多少个电子？（原子序数 %d）" % (s, z), z, [z + 1, z - 1, last, 2 * z], "", "原子中电子数 = 质子数 = 原子序数。")
    return nq("%s 原子（原子序数 %d）最外层有几个电子？" % (s, z), last, [per, z, 8 - last, last + 1], "", "核外电子排布：%s。" % "，".join(str(x) for x in out))


