        return nq("%s %d km를 %d시간 동안 달렸습니다. 속력은 몇 km/h일까요?" % (josa(car, "이/가"), d, t), v, [d * t, d + t, v * 2, v + 10], "km/h", "%d ÷ %d = %d km/h입니다." % (d, t, v))
