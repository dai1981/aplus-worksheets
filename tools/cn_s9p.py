WATER_C = 4.2e3


def f_heat(R):
    k = R.choice(["Q", "dt", "fuel", "eff"])
    if k == "Q":
        m = R.choice([0.5, 1, 2, 3, 5])
        dt = R.choice([10, 20, 30, 40, 50, 80])
        Q = WATER_C * m * dt
        return nq("把 %s kg 的水从 20 ℃ 加热，温度升高 %d ℃，吸收多少热量？（c水 = 4.2×10³ J/(kg·℃)）" % (num(m), dt), Q, [WATER_C * m, WATER_C * dt, Q / 1000], "J",
                  "Q = cmΔt = 4.2×10³ × %s × %d = %s J。" % (num(m), dt, num(Q)))
    if k == "dt":
        m = R.choice([1, 2, 4, 5])
        Q = R.choice([8.4e4, 1.68e5, 4.2e5, 8.4e5])
        dt = Q / (WATER_C * m)
        if dt != int(dt) or dt > 80:
            return None
        return nq("%s kg 的水吸收 %s J 的热量，温度升高多少？（c水 = 4.2×10³ J/(kg·℃)）" % (num(m), num(Q)), dt, [Q / WATER_C, dt * m * m, dt + 20], "℃",
                  "Δt = Q/(cm) = %s ÷ (4.2×10³ × %s) = %s ℃。" % (num(Q), num(m), num(dt)))
    if k == "fuel":
        f = R.choice([("酒精", 3.0e7, "3.0×10⁷"), ("煤", 3.0e7, "3.0×10⁷"), ("汽油", 4.6e7, "4.6×10⁷"), ("天然气", 4.0e7, "4.0×10⁷")])
        m = R.choice([0.1, 0.2, 0.5, 1, 2])
        return nq("完全燃烧 %s kg %s放出多少热量？（热值 %s J/kg）" % (num(m), f[0], f[2]), f[1] * m, [f[1] / m, f[1], f[1] * m * 10], "J",
                  "Q = mq = %s × %s = %s J。" % (num(m), f[2], num(f[1] * m)))
    use = R.choice([2.1e6, 4.2e6, 6.3e6])
    tot = R.choice([1e7, 1.2e7, 2e7])
    e = use / tot * 100
    return nq("燃料完全燃烧放出 %s J 的热量，水吸收了 %s J，加热效率是多少？" % (num(tot), num(use)), e, [tot / use * 100, 100 - e, e / 10], "%", "η = Q吸/Q放 = %s%%。" % num(e))


