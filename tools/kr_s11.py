    if k == "field":
        F, q = R.choice([(6, 2), (10, 5), (0.4, 0.2), (12, 3), (20, 4)])
        return nq("전기장 안의 한 점에 %s C의 전하를 놓았더니 %s N의 전기력을 받았습니다. 이 점의 전기장의 세기는 몇 N/C일까요?" % (num(q), num(F)), F / q, [F * q, q / F, F + q], "N/C", "E = F ÷ q = %s ÷ %s = %s N/C입니다." % (num(F), num(q), num(F / q)))
