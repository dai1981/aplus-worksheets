    if k == "n":
        name, M = R.choice(MM)
        n = R.choice([0.5, 2, 3, 0.1, 0.2, 1.5])
        return nq("%s %s g은 몇 mol일까요? (화학식량: %s)" % (name, num(M * n), num(M)), n, [M * n * M, M / (M * n), n * 2, n / 2], "mol", "몰수 = 질량 ÷ 몰 질량 = %s ÷ %s = %s mol입니다." % (num(M * n), num(M), num(n)))
    if k == "N":
        n = R.choice([0.5, 2, 3, 0.1, 1.5, 0.25])
        return nq("어떤 분자 %s mol에 들어 있는 분자 수는 몇 개일까요? (아보가드로수 6×10²³)" % num(n), 6e23 * n, [6e23 / n, 6e23 * n * 10, 6e23], "개", "%s × 6×10²³ = %s개입니다." % (num(n), num(6e23 * n)))
    if k == "M":
        name, M = R.choice(MM)
        return nq("%s 1 mol의 질량은 몇 g일까요? (원자량: H 1, C 12, N 14, O 16, Na 23, Cl 35.5)" % name, M, [M / 2, M * 2, M + 1, M - 2], "g", "%s의 화학식량이 %s이므로 1 mol의 질량은 %s g입니다." % (name, num(M), num(M)))
    if k == "c":
        n, V = R.choice([(0.2, 0.5), (0.1, 0.1), (0.5, 0.25), (1, 2), (0.3, 0.6), (2, 1)])
