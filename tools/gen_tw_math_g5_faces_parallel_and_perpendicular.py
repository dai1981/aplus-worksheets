def s4(seen):
    def mk():
        a, b, c = R.randint(3, 15), R.randint(2, 12), R.randint(2, 12)
        a, b = max(a, b), min(a, b)
        kind = R.choice(["par", "perp", "dist"])
        if kind == "par":
            q = "長 %d 公分、寬 %d 公分、高 %d 公分的長方體，和上面平行的面面積是多少？" % (a, b, c)
            return mcq(q, "%d 平方公分" % (a * b), ["%d 平方公分" % x for x in (a * c, b * c, a * b * c) if x != a * b], "和上面平行的是下面，一樣大：%d × %d ＝ %d（平方公分）。" % (a, b, a * b))
        if kind == "perp":
            q = "長 %d 公分、寬 %d 公分、高 %d 公分的長方體，和上面垂直的 4 個面，面積一共是多少？" % (a, b, c)
            v = 2 * (a * c + b * c)
            return mcq(q, "%d 平方公分" % v, ["%d 平方公分" % x for x in (a * c + b * c, 2 * (a * b + b * c + a * c), 4 * a * c) if x != v], "前後 %d × %d × 2，左右 %d × %d × 2，合計 %d（平方公分）。" % (a, c, b, c, v))
        q = "長 %d 公分、寬 %d 公分、高 %d 公分的長方體，上面和下面兩個平行面之間的距離是幾公分？" % (a, b, c)
        return mcq(q, "%d 公分" % c, ["%d 公分" % x for x in (a, b, a + b) if x != c] + ["%d 公分" % (c * 2)], "上面和下面之間的距離就是高：%d 公分。" % c)
    return pick_unique(R, mk, 20, seen)


def s5(seen):
    def net():
        pairs = [("1", "6"), ("2", "5"), ("3", "4")]
        a, b = R.choice(pairs)
        if R.random() < .5:
            a, b = b, a
        q = "骰子相對的面點數加起來是 7。和「%s 點」那一面平行的是幾點？" % a
        others = [str(x) for x in range(1, 7) if str(x) not in (a, b)]
        return mcq(q, "%s 點" % b, ["%s 點" % x for x in R.sample(others, 3)], "相對的面互相平行，%s ＋ %s ＝ 7。" % (a, b))

    def count():
        k = R.choice([("正方體", 3, 12), ("長方體", 3, 12)])
        if R.random() < .5:
            q = "%s裡，每一組平行的面各有 2 個面，%d 組一共有幾個面？" % (k[0], k[1])
            return mcq(q, "6 個", ["3 個", "4 個", "12 個"], "%d × 2 ＝ 6，剛好是所有的面。" % k[1])
        q = "把一個長方體紙箱放在桌上，和桌面互相垂直的面有幾個？"
        return mcq(q, "4 個", ["1 個", "2 個", "6 個"], "貼在桌面的是下面，前後左右 4 個面都和桌面垂直。")
    out = pick_unique(R, net, 6, seen)
    extra = [mcq("把一個長方體紙箱放在桌上，和桌面互相平行的面有幾個？", "1 個（上面）", ["2 個", "4 個", "沒有"], "下面貼著桌面，上面和桌面平行。"),
             mcq("正方體的展開圖中，隔一個面的兩個面摺起來後是什麼關係？", "互相平行", ["互相垂直", "重合", "相鄰"], "一排連續的面，隔一個的會變成相對的面，互相平行。"),
             mcq("正方體的展開圖中，相鄰（有一條共同邊）的兩個面摺起來後是什麼關係？", "互相垂直", ["互相平行", "重合", "相對"], "有共同邊的兩個面摺起來會相交成直角。")]
    for e in extra:
        seen.add(e["q"])

    def mixed():
        f, g = R.sample(FACES, 2)
        q = "長方體的%s和%s是什麼關係？" % (f, g)
        rel = "互相平行" if OPP[f] == g else "互相垂直"
        return mcq(q, rel, ["互相垂直" if rel == "互相平行" else "互相平行", "會重合", "沒有關係"], "%s。" % ("相對的面平行" if rel == "互相平行" else "相鄰的面垂直"))
    return out + extra + pick_unique(R, mixed, 11, seen)


