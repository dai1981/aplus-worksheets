def s1(seen):
    def mk():
        f = R.choice(FACES)
        solid = R.choice(["長方體", "正方體", "紙箱", "骰子"])
        q = "%s的%s和哪一個面平行？" % (solid, f)
        others = [x for x in FACES if x not in (f, OPP[f])]
        return mcq(q, OPP[f], R.sample(others, 3), "相對（面對面）的兩個面互相平行：%s和%s。" % (f, OPP[f]))
    return pick_unique(R, mk, 20, seen) if False else [mk() for _ in range(0)] + pick_unique(R, mk, 20, seen) if len(FACES) * 4 >= 20 else []


def s2(seen):
    def mk():
        f = R.choice(FACES)
        solid = R.choice(["長方體", "正方體", "紙箱", "骰子"])
        adj = [x for x in FACES if x not in (f, OPP[f])]
        if R.random() < .5:
            q = "%s的%s和幾個面垂直？" % (solid, f)
            return mcq(q, "4 個", ["1 個", "2 個", "5 個"], "和%s相鄰的面都和它垂直：%s，共 4 個。" % (f, "、".join(adj)))
        g = R.choice(adj)
        q = "%s的%s和%s是什麼關係？" % (solid, f, g)
        return mcq(q, "互相垂直", ["互相平行", "沒有關係", "一樣大"], "%s和%s相鄰，相交成直角，互相垂直。" % (f, g))
    return pick_unique(R, mk, 20, seen)


