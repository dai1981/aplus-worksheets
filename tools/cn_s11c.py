def f_rate(R):
    k = R.choice(["v", "ratio", "K", "ph", "ph2", "kw", "dH"])
    if k == "v":
        dc, t = R.choice([(1.2, 2), (0.6, 3), (2, 5), (0.8, 4), (1.5, 10)])
        return nq("某反应中 A 的浓度在 %d min 内减少了 %s mol/L，用 A 表示的平均反应速率是多少？" % (t, num(dc)), dc / t, [dc * t, t / dc, dc], "mol/(L·min)", "v = Δc/Δt = %s mol/(L·min)。" % num(dc / t))
    if k == "ratio":
        a, b = R.choice([(0.2, 1), (0.3, 1), (0.6, 3), (0.4, 1)])
        return nq("对于 N₂ + 3H₂ ⇌ 2NH₃，v(N₂) = %s mol/(L·min)，则 v(NH₃) 是多少？" % num(a), 2 * a, [a, 3 * a, a / 2], "mol/(L·min)", "速率之比等于化学计量数之比：v(NH₃) = 2v(N₂)。")
    if k == "K":
        a, b, c = R.choice([(0.5, 0.5, 1), (0.2, 0.4, 0.4), (1, 2, 2), (0.1, 0.2, 0.2)])
        return nq("对于 A(g) + B(g) ⇌ C(g)，平衡时 c(A) = %s mol/L，c(B) = %s mol/L，c(C) = %s mol/L，平衡常数 K 是多少？" % (num(a), num(b), num(c)), c / (a * b), [a * b / c, c / (a + b), c], "",
                  "K = c(C)/[c(A)·c(B)] = %s。" % num(c / (a * b)))
    if k == "ph":
        n = R.choice([1, 2, 3, 4])
        return nq("25 ℃ 时，c(H⁺) = 10⁻%s mol/L 的盐酸，pH 是多少？" % str(n).translate(str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹")), n, [14 - n, n + 1, 10 * n], "", "pH = −lg c(H⁺) = %d。" % n)
    if k == "ph2":
        n = R.choice([1, 2, 3, 4])
        return nq("25 ℃ 时，c(OH⁻) = 10⁻%s mol/L 的 NaOH 溶液，pH 是多少？" % str(n).translate(str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹")), 14 - n, [n, 7 + n, 14 + n], "", "c(H⁺) = Kw/c(OH⁻) = 10^−%d，pH = %d。" % (14 - n, 14 - n))
    if k == "kw":
        n = R.choice([2, 3, 4, 5])
        return it("25 ℃ 时某溶液 pH = %d，它的 c(OH⁻) 是多少？" % n, "10⁻%s mol/L" % str(14 - n).translate(str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹")),
                  ["10⁻%s mol/L" % str(n).translate(str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹")), "10⁻⁷ mol/L", "10⁻¹⁴ mol/L"], "Kw = c(H⁺)·c(OH⁻) = 1×10⁻¹⁴。")
    a, b = R.choice([(-286, 2), (-890, 1), (-393.5, 3), (-571.6, 0.5), (-283, 2)])
    return it("某反应 ΔH = %s kJ/mol，若按方程式的 %s 倍进行反应，放出多少热量？" % (num(a), num(b)), "%s kJ" % num(-a * b), ["%s kJ" % num(-a), "%s kJ" % num(-a / b), "%s kJ" % num(-a * b * 2)],
              "ΔH 与化学计量数成正比。")


def f_cell(R):
    k = R.choice(["e", "cu", "ag", "h2"])
    if k == "e":
        n = R.choice([0.1, 0.2, 0.5, 1])
        return nq("电解 CuCl₂ 溶液时，阴极析出 %s mol Cu，电路中转移电子多少摩尔？" % num(n), 2 * n, [n, n / 2, 4 * n], "mol", "Cu²⁺ + 2e⁻ ═ Cu，转移电子 %s mol。" % num(2 * n))
    if k == "cu":
        n = R.choice([0.2, 0.4, 1, 2])
        return nq("电解硫酸铜溶液，电路中通过 %s mol 电子，阴极析出铜多少克？（Cu-64）" % num(n), n / 2 * 64, [n * 64, n / 4 * 64, n * 32 * 4], "g", "析出 Cu %s mol，质量 %s g。" % (num(n / 2), num(n / 2 * 64)))
    if k == "ag":
        n = R.choice([0.1, 0.2, 0.5])
        return nq("用惰性电极电解 AgNO₃ 溶液，阴极析出 %s mol Ag，阳极产生 O₂ 多少摩尔？" % num(n), n / 4, [n, n / 2, n * 4], "mol", "转移电子 %s mol，4OH⁻ − 4e⁻ ═ O₂↑ + 2H₂O。" % num(n))
    n = R.choice([0.2, 0.5, 1, 2])
    return nq("氢氧燃料电池中消耗 %s mol H₂，电路中转移电子多少摩尔？" % num(n), 2 * n, [n, 4 * n, n / 2], "mol", "H₂ − 2e⁻ → 2H⁺。")


def f_struct(R):
    E = [("C", 6, "1s²2s²2p²"), ("N", 7, "1s²2s²2p³"), ("O", 8, "1s²2s²2p⁴"), ("F", 9, "1s²2s²2p⁵"), ("Na", 11, "1s²2s²2p⁶3s¹"), ("Mg", 12, "1s²2s²2p⁶3s²"), ("Al", 13, "1s²2s²2p⁶3s²3p¹"),
         ("Si", 14, "1s²2s²2p⁶3s²3p²"), ("P", 15, "1s²2s²2p⁶3s²3p³"), ("S", 16, "1s²2s²2p⁶3s²3p⁴"), ("Cl", 17, "1s²2s²2p⁶3s²3p⁵"), ("K", 19, "1s²2s²2p⁶3s²3p⁶4s¹"), ("Ca", 20, "1s²2s²2p⁶3s²3p⁶4s²")]
    k = R.choice(["conf", "who", "unp", "geo", "hyb"])
    if k == "conf":
        s, z, c = R.choice(E)
        w = [x[2] for x in E if x[0] != s]
        R.shuffle(w)
        return it("%s 原子（原子序数 %d）基态的电子排布式是什么？" % (s, z), c, sorted(w[:3]), "按构造原理 1s 2s 2p 3s 3p 4s 的顺序填充。")
    if k == "who":
        s, z, c = R.choice(E)
        w = [x[0] for x in E if x[0] != s]
        R.shuffle(w)
        return it("基态原子电子排布式为 %s 的元素是哪一种？" % c, s, sorted(w[:3]), "数一数电子总数 = %d。" % z)
    if k == "unp":
        s, n = R.choice([("C", 2), ("N", 3), ("O", 2), ("F", 1), ("Na", 1), ("Mg", 0), ("P", 3), ("S", 2), ("Cl", 1), ("Si", 2), ("Al", 1)])
        return nq("基态 %s 原子中有几个未成对电子？" % s, n, [n + 1, n + 2, 4 - n if 4 - n != n else 5], "", "按洪特规则，p 轨道电子先分占不同轨道且自旋平行。") if n else \
            it("基态 Mg 原子中有几个未成对电子？", "0 个", ["1 个", "2 个", "3 个"], "3s² 两个电子已成对。")
    if k == "geo":
        m, g = R.choice([("CO₂", "直线形"), ("H₂O", "V 形"), ("NH₃", "三角锥形"), ("CH₄", "正四面体形"), ("BF₃", "平面三角形"), ("BeCl₂", "直线形"), ("SO₂", "V 形"), ("CCl₄", "正四面体形")])
        w = [x for x in ["直线形", "V 形", "三角锥形", "正四面体形", "平面三角形"] if x != g]
        R.shuffle(w)
        return it("%s 分子的空间结构是什么？" % m, g, w[:3], "用价层电子对互斥模型判断。")
    m, g = R.choice([("CH₄", "sp³"), ("C₂H₄", "sp²"), ("C₂H₂", "sp"), ("BF₃", "sp²"), ("CO₂", "sp"), ("NH₃", "sp³"), ("H₂O", "sp³"), ("苯", "sp²")])
    w = [x for x in ["sp", "sp²", "sp³", "dsp²"] if x != g]
    return it("%s 中心原子（或碳原子）的杂化方式是什么？" % m, g, w, "根据价层电子对数判断：2 对 sp，3 对 sp²，4 对 sp³。")


