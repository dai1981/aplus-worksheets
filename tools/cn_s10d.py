def f_air(R):
    k = R.choice(["alt", "alt2", "diff"])
    if k == "alt":
        t, h = R.choice([20, 25, 28, 30, 32]), R.choice([1000, 1500, 2000, 3000, 4000])
        return nq("对流层中海拔每升高 1000 m 气温约下降 6 ℃。山脚气温 %d ℃，海拔 %d m 的山顶气温约为多少？" % (t, h), t - 6 * h / 1000, [t + 6 * h / 1000, t - h / 1000, t - 6], "℃",
                  "%d − 6 × %s = %s ℃。" % (t, num(h / 1000), num(t - 6 * h / 1000)))
    if k == "alt2":
        a, b = R.choice([(24, 12), (30, 18), (26, 8), (20, 2), (28, 16)])
        return nq("某山山脚气温 %d ℃，山顶气温 %d ℃，按每升高 1000 m 下降 6 ℃ 计算，山的相对高度约是多少？" % (a, b), (a - b) / 6 * 1000, [(a - b) * 100, (a - b) * 1000, (a - b) / 6 * 100], "m",
                  "(%d − %d) ÷ 6 × 1000 = %s m。" % (a, b, num((a - b) / 6 * 1000)))
    a, b = R.choice([(15, 3), (18, 6), (22, 10)])
    return nq("某地一天中最高气温 %d ℃，最低气温 %d ℃，气温日较差是多少？" % (a, b), a - b, [a + b, (a + b) / 2, a], "℃", "日较差 = 最高气温 − 最低气温 = %d ℃。" % (a - b))


def f_pop(R):
    k = R.choice(["nat", "urb", "dens", "net"])
    if k == "nat":
        b, d = R.choice([(12, 7), (15, 8), (10, 11), (20, 6), (8, 9), (14, 10), (11, 6), (18, 9), (25, 8), (9, 12), (13, 5), (16, 7)])
        return nq("某地出生率为 %d‰，死亡率为 %d‰，人口自然增长率是多少？（用 ‰ 表示的数值）" % (b, d), b - d if b > d else None, [b + d, b, d], "‰", "自然增长率 = 出生率 − 死亡率。") if b > d else \
            it("某地出生率为 %d‰，死亡率为 %d‰，人口自然增长率是多少？" % (b, d), "−%d‰" % (d - b), ["%d‰" % (d - b), "%d‰" % (b + d), "0"], "出生率低于死亡率，人口自然增长率为负。")
    if k == "urb":
        u, t = R.choice([(66, 100), (45, 90), (32, 80), (54, 120), (7, 10), (36, 60), (42, 70), (18, 40), (75, 100), (24, 30), (60, 75)])
        return nq("某地总人口 %d 万，城镇人口 %d 万，城镇化率是多少？" % (t, u), u / t * 100, [u, (t - u) / t * 100, t / u * 100], "%", "城镇化率 = 城镇人口 ÷ 总人口 × 100%% = %s%%。" % num(u / t * 100))
    if k == "dens":
        p, a = R.choice([(120, 4), (300, 10), (50, 25), (800, 16), (600, 20), (90, 30), (450, 15), (1000, 8)])
        return nq("某地面积 %d 万 km²，人口 %d 万，人口密度是多少？" % (a, p), p / a, [a / p, p * a, p], "人/km²", "人口密度 = 人口 ÷ 面积 = %s 人/km²。" % num(p / a))
    i, o = R.choice([(30, 12), (50, 20), (8, 15), (25, 25), (40, 16), (12, 30), (60, 45), (5, 9)])
    if i == o:
        return None
    v = i - o
    return it("某城市一年迁入 %d 万人，迁出 %d 万人，人口净迁移是多少？" % (i, o), ("净迁入 %d 万人" % v) if v > 0 else ("净迁出 %d 万人" % -v),
              [("净迁出 %d 万人" % abs(v)) if v > 0 else ("净迁入 %d 万人" % abs(v)), "净迁入 %d 万人" % (i + o), "没有变化"], "净迁移 = 迁入 − 迁出。")


