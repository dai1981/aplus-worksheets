    if k == "I":
        n1, n2, U1 = R.choice([(1100, 55, 220), (100, 500, 20), (2000, 100, 220), (400, 20, 200)])
        return nq("理想变压器原线圈 %d 匝、副线圈 %d 匝，原线圈输入电压 %d V，副线圈输出电压是多少？" % (n1, n2, U1), U1 * n2 / n1, [U1 * n1 / n2, U1, U1 * n2], "V", "U₁/U₂ = n₁/n₂，U₂ = %s V。" % num(U1 * n2 / n1))
    Um = R.choice([311, 220 * 1.414, 100, 14.14])
    return nq("正弦式交变电流电压的峰值为 %s V，有效值约是多少？" % num(Um), Um / 1.414, [Um, Um * 1.414, Um / 2], "V", "有效值 = 峰值 ÷ √2。")


