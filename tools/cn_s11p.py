def f_elec(R):
    k = R.choice(["coul", "E", "W", "C", "ohm", "ser", "par", "P", "emf"])
    if k == "coul":
        n = R.choice([2, 3, 4])
        return it("两个点电荷之间的距离变为原来的 %d 倍，电荷量不变，库仑力变为原来的多少？" % n, "1/%d" % (n * n), ["1/%d" % n, "%d 倍" % n, "%d 倍" % (n * n)], "F = kq₁q₂/r²，与距离的平方成反比。")
    if k == "E":
        F, q = R.choice([(2e-3, 1e-6), (4e-4, 2e-8), (6e-3, 3e-6), (1e-2, 5e-6)])
        return nq("电荷量为 %s C 的试探电荷在电场中某点受到的电场力为 %s N，该点的电场强度是多少？" % (num(q), num(F)), F / q, [F * q, q / F, F / q / 10], "N/C", "E = F/q = %s N/C。" % num(F / q))
    if k == "W":
        q, U = R.choice([(2e-6, 100), (5e-8, 400), (1e-6, 2000), (3e-6, 50)])
        return nq("电荷量为 %s C 的正电荷从 A 点移到 B 点，A、B 间电势差为 %d V，电场力做功多少？" % (num(q), U), q * U, [q / U, U / q, q * U * 10], "J", "W = qU = %s J。" % num(q * U))
    if k == "C":
        Q, U = R.choice([(6e-4, 30), (2e-5, 10), (1e-3, 50), (4e-6, 2)])
        return nq("电容器两极板间电压为 %d V 时所带电荷量为 %s C，它的电容是多少？" % (U, num(Q)), Q / U, [Q * U, U / Q, Q / U * 1000], "F", "C = Q/U = %s F。" % num(Q / U))
    if k == "ohm":
        U, I = R.choice([(6, 0.5), (12, 2), (3, 0.2), (220, 0.5), (9, 0.3)])
        return nq("导体两端电压为 %s V，通过的电流为 %s A，它的电阻是多少？" % (num(U), num(I)), U / I, [U * I, I / U, U / I / 2], "Ω", "R = U/I = %s Ω。" % num(U / I))
    if k == "ser":
        a, b, U = R.choice([(4, 6, 10), (10, 20, 6), (2, 8, 5), (5, 15, 12)])
        return nq("%d Ω 和 %d Ω 的电阻串联接在 %d V 的电源上（不计内阻），电路中的电流是多少？" % (a, b, U), U / (a + b), [U / a, U / b, U / (a * b / (a + b))], "A", "I = U/(R₁ + R₂) = %s A。" % num(U / (a + b)))
    if k == "par":
        a, b = R.choice([(6, 3), (4, 4), (12, 6), (10, 15), (20, 30)])
        return nq("%d Ω 和 %d Ω 的电阻并联，总电阻是多少？" % (a, b), a * b / (a + b), [a + b, (a + b) / 2, abs(a - b) or a * 2], "Ω", "R = R₁R₂/(R₁ + R₂) = %s Ω。" % num(a * b / (a + b)))
    if k == "P":
        U, R_ = R.choice([(220, 484), (220, 1100), (12, 6), (6, 12)])
        return nq("电阻为 %d Ω 的用电器接在 %d V 电压下，消耗的电功率是多少？" % (R_, U), U * U / R_, [U / R_, U * R_, U * U / R_ / 2], "W", "P = U²/R = %s W。" % num(U * U / R_))
    E, r, R_ = R.choice([(6, 1, 5), (3, 0.5, 2.5), (12, 2, 4), (9, 1, 2), (1.5, 0.5, 1)])
    return nq("电源电动势为 %s V，内阻为 %s Ω，外电阻为 %s Ω，电路中的电流是多少？" % (num(E), num(r), num(R_)), E / (R_ + r), [E / R_, E / r, E * (R_ + r)], "A", "闭合电路欧姆定律 I = E/(R + r) = %s A。" % num(E / (R_ + r)))


def f_mom(R):
    k = R.choice(["p", "imp", "coll", "stick", "recoil", "F"])
    if k == "p":
        m, v = R.choice([(2, 3), (0.5, 10), (60, 5), (1000, 20), (0.2, 15)])
        return nq("质量 %s kg 的物体以 %s m/s 的速度运动，它的动量大小是多少？" % (num(m), num(v)), m * v, [m * v * v / 2, m / v, m * v * 2], "kg·m/s", "p = mv = %s kg·m/s。" % num(m * v))
    if k == "imp":
        F, t = R.choice([(10, 2), (50, 0.2), (200, 0.05), (5, 4)])
        return nq("%s N 的恒力作用在物体上 %s s，力的冲量大小是多少？" % (num(F), num(t)), F * t, [F / t, F * t * 2, t / F], "N·s", "I = Ft = %s N·s。" % num(F * t))
    if k == "coll":
        m1, v1, m2 = R.choice([(1, 6, 2), (2, 4, 2), (3, 5, 2), (1, 10, 4)])
        v = m1 * v1 / (m1 + m2)
        return nq("质量 %d kg 的小球以 %d m/s 的速度与静止的质量 %d kg 的小球相碰，碰后粘在一起，共同速度是多少？" % (m1, v1, m2), v, [v1, v1 / 2, m1 * v1 / m2], "m/s", "动量守恒 m₁v₁ = (m₁ + m₂)v，v = %s m/s。" % num(v))
    if k == "stick":
        m, M, v = R.choice([(0.01, 0.99, 300), (0.02, 1.98, 200), (0.05, 0.95, 100)])
        V = m * v / (m + M)
        return nq("质量 %s kg 的子弹以 %d m/s 射入静止在光滑水平面上的 %s kg 木块并留在其中，木块的速度是多少？" % (num(m), v, num(M)), V, [m * v / M * 10, v, m * v], "m/s", "动量守恒：v = mv₀/(m + M) = %s m/s。" % num(V))
    if k == "recoil":
        m, v, M = R.choice([(50, 2, 100), (60, 3, 120), (40, 1.5, 200)])
        return nq("静止在冰面上的人（%d kg）把一个物体推出，物体质量 %d kg，速度 %s m/s，人后退的速度是多少？" % (M, m, num(v)), m * v / M, [v, M * v / m, m * v], "m/s", "系统总动量为零：Mv人 = mv物。")
    m, v, t = R.choice([(0.5, 10, 0.1), (0.2, 20, 0.05), (60, 5, 0.5)])
    return nq("质量 %s kg 的物体以 %d m/s 的速度撞墙后停下，作用时间 %s s，墙对物体的平均作用力是多少？" % (num(m), v, num(t)), m * v / t, [m * v * t, m * v, m * v / t / 2], "N", "动量定理 Ft = Δp，F = %s N。" % num(m * v / t))


def f_wave(R):
    k = R.choice(["v", "f", "T", "pend", "lam", "n"])
    if k == "v":
        lam, f = R.choice([(2, 5), (0.5, 40), (4, 0.5), (1.5, 2)])
        return nq("一列波的波长为 %s m，频率为 %s Hz，波速是多少？" % (num(lam), num(f)), lam * f, [lam / f, f / lam, lam * f * 2], "m/s", "v = λf = %s m/s。" % num(lam * f))
    if k == "f":
        T = R.choice([0.2, 0.5, 0.02, 4])
        return nq("某振动的周期为 %s s，频率是多少？" % num(T), 1 / T, [T, 2 / T, 1 / (2 * T)], "Hz", "f = 1/T = %s Hz。" % num(1 / T))
    if k == "T":
        n, t = R.choice([(30, 60), (20, 40), (50, 10), (10, 25)])
        return nq("单摆在 %d s 内完成 %d 次全振动，周期是多少？" % (t, n), t / n, [n / t, t * n, t / n / 2], "s", "T = t/n = %s s。" % num(t / n))
    if k == "pend":
        n = R.choice([4, 9, 16])
        return it("单摆的摆长变为原来的 %d 倍，周期变为原来的几倍？" % n, "%d 倍" % int(n ** 0.5), ["%d 倍" % n, "1/%d" % int(n ** 0.5), "不变"], "T = 2π√(l/g)，周期与摆长的平方根成正比。")
    if k == "lam":
        v, f = R.choice([(340, 680), (340, 170), (1500, 500), (3e8, 1e8)])
        return nq("波速为 %s m/s、频率为 %s Hz 的波，波长是多少？" % (num(v), num(f)), v / f, [v * f, f / v, v / f * 2], "m", "λ = v/f = %s m。" % num(v / f))
    n = R.choice([1.5, 2, 1.33])
    return nq("光在折射率为 %s 的介质中的传播速度约是多少？（真空中光速取 3×10⁸ m/s）" % num(n), 3e8 / n, [3e8 * n, 3e8, 3e8 / n / 2], "m/s", "v = c/n。")


