def f_gas(R):
    k = R.choice(["boyle", "charles", "gay", "dU", "mol"])
    if k == "boyle":
        p1, V1, V2 = R.choice([(1, 10, 5), (2, 6, 4), (1, 20, 4), (3, 2, 6), (1.5, 8, 12)])
        return nq("一定质量的理想气体温度不变，压强为 %s atm 时体积为 %s L，体积变为 %s L 时压强是多少？" % (num(p1), num(V1), num(V2)), p1 * V1 / V2, [p1 * V2 / V1, p1, p1 * V1 * V2], "atm", "玻意耳定律 p₁V₁ = p₂V₂。")
    if k == "charles":
        V1, T1, T2 = R.choice([(3, 300, 400), (2, 300, 450), (6, 400, 200), (5, 250, 300)])
        return nq("一定质量的理想气体压强不变，温度为 %d K 时体积为 %d L，温度变为 %d K 时体积是多少？" % (T1, V1, T2), V1 * T2 / T1, [V1 * T1 / T2, V1 + T2 - T1, V1], "L", "盖-吕萨克定律 V₁/T₁ = V₂/T₂。")
    if k == "gay":
        p1, t1, t2 = R.choice([(1, 27, 127), (2, 27, 327), (1, 127, 27), (1.5, 27, 227)])
        T1, T2 = t1 + 273, t2 + 273
        return nq("密闭容器中气体体积不变，%d ℃ 时压强为 %s atm，%d ℃ 时压强是多少？" % (t1, num(p1), t2), p1 * T2 / T1, [p1 * t2 / t1, p1 * T1 / T2, p1], "atm", "查理定律 p₁/T₁ = p₂/T₂，温度要用热力学温度。")
    if k == "dU":
        W, Q = R.choice([(200, 300), (500, -200), (-100, 400), (300, -300), (800, -500)])
        return it("外界对气体做功 %d J，气体%s热量 %d J，气体内能变化多少？" % (W, "吸收" if Q > 0 else "放出", abs(Q)) if W > 0 else
                  "气体对外界做功 %d J，同时吸收热量 %d J，气体内能变化多少？" % (-W, Q),
                  ("增加 %d J" % (W + Q)) if W + Q > 0 else ("减少 %d J" % -(W + Q)) if W + Q < 0 else "不变",
                  [x for x in ["增加 %d J" % abs(W - Q), "减少 %d J" % abs(W + Q), "增加 %d J" % (abs(W) + abs(Q)), "不变"] if x != (("增加 %d J" % (W + Q)) if W + Q > 0 else ("减少 %d J" % -(W + Q)) if W + Q < 0 else "不变")][:3],
                  "热力学第一定律 ΔU = W + Q（外界对气体做功 W 为正，吸热 Q 为正）。")
    t = R.choice([0, 27, 100, -73, 37, 127])
    return nq("%d ℃ 相当于多少开尔文（K）？" % t, t + 273, [t, 273 - t, t + 373], "K", "T = t + 273 K。")


def f_mod(R):
    k = R.choice(["photon", "hl", "hl2", "level", "pe", "E"])
    if k == "photon":
        n = R.choice([2, 3, 4])
        return it("用某种频率的光照射金属发生光电效应，若光强增大到原来的 %d 倍而频率不变，光电子的最大初动能怎样变？" % n, "不变", ["变为 %d 倍" % n, "变为 1/%d" % n, "变为 %d 倍" % (n * n)], "最大初动能只与入射光频率有关，与光强无关。")
    if k == "hl":
        T, t = R.choice([(5, 10), (8, 24), (2, 6), (1600, 3200), (5730, 11460)])
        n = t // T
        return it("某放射性元素的半衰期为 %d 天，经过 %d 天后，剩余未衰变的原子核占原来的多少？" % (T, t), "1/%d" % (2 ** n), ["1/%d" % n, "1/%d" % (2 * n) if 2 * n != 2 ** n else "1/%d" % (2 ** n * 2), "1/%d" % (2 ** (n + 1))],
                  "经过 %d 个半衰期，剩余 (1/2)^%d。" % (n, n))
    if k == "hl2":
        m, T, t = R.choice([(100, 5, 10), (80, 3, 9), (64, 2, 8), (200, 10, 30)])
        return nq("%d g 某放射性元素的半衰期是 %d 天，%d 天后还剩多少克没有衰变？" % (m, T, t), m / 2 ** (t // T), [m / (t // T), m / 2, m - m / 2 ** (t // T)], "g", "剩余质量 m = m₀(1/2)^(t/T)。")
    if k == "level":
        n = R.choice([3, 4, 5])
        return nq("一群氢原子处于 n = %d 的激发态，向低能级跃迁时最多能发出几种频率的光？" % n, n * (n - 1) // 2, [n - 1, n, n * n], "", "种数 = n(n − 1)/2 = %d。" % (n * (n - 1) // 2))
    if k == "pe":
        W, hv = R.choice([(2.25, 4.25), (3.2, 5), (1.9, 3.1), (4.5, 6.2)])
        return nq("金属的逸出功为 %s eV，用能量为 %s eV 的光子照射，光电子的最大初动能是多少？" % (num(W), num(hv)), hv - W, [hv + W, hv, W], "eV", "爱因斯坦光电效应方程 Eₖ = hν − W₀。")
    E1, n = -13.6, R.choice([2, 3, 4])
    return nq("氢原子基态能量为 −13.6 eV，处于第 %d 能级的氢原子至少要吸收多少能量才能电离？" % n, 13.6 / n / n, [13.6 / n, 13.6 * n, 13.6 / (n + 1)], "eV", "Eₙ = E₁/n² = −%s eV，电离需要吸收 %s eV。" % (num(13.6 / n / n), num(13.6 / n / n)))


