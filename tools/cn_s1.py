def cmp_len(R):
    things = ["铅笔", "橡皮", "尺子", "绳子", "彩带", "书本", "筷子", "吸管", "毛线", "木条"]
    a, b = R.sample(things, 2)
    x, y = R.sample(range(2, 15), 2)
    k = R.choice(["clip", "box", "step"])
    unit = {"clip": "个回形针", "box": "个小方块", "step": "拃"}[k]
    if R.random() < 0.5:
        return __import__("cn_sci").it("%s有 %d %s长，%s有 %d %s长。哪个更长？" % (a, x, unit, b, y, unit),
                                      a if x > y else b, [b if x > y else a, "一样长", "无法比较"], "%d 比 %d %s，所以%s更长。" % (max(x, y), min(x, y), "多", a if x > y else b))
    return __import__("cn_sci").it("%s有 %d %s长，%s有 %d %s长。哪个更短？" % (a, x, unit, b, y, unit),
                                  a if x < y else b, [b if x < y else a, "一样长", "无法比较"], "%d 比 %d 少，所以%s更短。" % (min(x, y), max(x, y), a if x < y else b))


def clip(R):
    import cn_sci
    t = R.choice(["铅笔", "课本", "橡皮", "尺子", "铅笔盒", "胶棒", "卡片"])
    n = R.randint(2, 12)
    k = R.choice(["count", "gap", "overlap"])
    if k == "count":
        return cn_sci.it("用回形针首尾相连地量%s，正好排了 %d 个。%s有几个回形针长？" % (t, n, t), "%d 个" % n, ["%d 个" % (n + 1), "%d 个" % (n - 1), "%d 个" % (n + 2)],
                         "排了几个回形针，就有几个回形针长。")
    if k == "gap":
        return cn_sci.it("小明量%s时，回形针之间留了空隙，数出 %d 个。真正的长度会怎样？" % (t, n), "比 %d 个回形针长" % n, ["比 %d 个回形针短" % n, "正好 %d 个回形针长" % n, "是 0"],
                         "留了空隙，空隙的地方没有数，所以真正的长度比数出来的长。")
    return cn_sci.it("小红量%s时，回形针重叠在一起，数出 %d 个。真正的长度会怎样？" % (t, n), "比 %d 个回形针短" % n, ["比 %d 个回形针长" % n, "正好 %d 个回形针长" % n, "是 0"],
                     "重叠的部分被多数了，所以真正的长度比数出来的短。")


def ruler(R):
    import cn_sci
    t = R.choice(["铅笔", "橡皮", "小刀", "胶棒", "蜡笔", "钥匙", "发卡", "树叶"])
    if R.random() < 0.5:
        n = R.randint(3, 19)
        return cn_sci.it("%s的一端对准尺子的 0 刻度，另一端对准 %d。%s长多少？" % (t, n, t), "%d 厘米" % n, ["%d 厘米" % (n + 1), "%d 厘米" % (n - 1), "%d 米" % n],
                         "从 0 开始，另一端对着几，就是几厘米。")
    a = R.randint(1, 6)
    n = R.randint(3, 10)
    return cn_sci.it("%s的一端对准尺子的 %d 刻度，另一端对准 %d。%s长多少？" % (t, a, a + n, t), "%d 厘米" % n, ["%d 厘米" % (a + n), "%d 厘米" % (n + 1), "%d 厘米" % a],
                     "没有从 0 开始，要用 %d − %d = %d（厘米）。" % (a + n, a, n))


def heavier(R):
    import cn_sci
    pairs = [("一块石头", "一团棉花", "一块石头"), ("一个铁球", "一个同样大的乒乓球", "一个铁球"), ("一本字典", "一张纸", "一本字典"),
             ("一瓶水", "一个空瓶子", "一瓶水"), ("一个苹果", "一颗葡萄", "一个苹果"), ("一块砖", "一块同样大的泡沫", "一块砖"),
             ("一个西瓜", "一个橘子", "一个西瓜"), ("一把铁锁", "一片树叶", "一把铁锁")]
    a, b, h = R.choice(pairs)
    if R.random() < 0.5:
        return cn_sci.it("%s和%s，哪个更重？" % (a, b), h, [b, "一样重", "无法比较"], "%s更重。" % h)
    l = b if h == a else a
    k = R.choice(["天平", "简易天平"])
    return cn_sci.it("用%s比较%s和%s，哪一边会往下沉？" % (k, a, b), "放%s的一边" % h, ["放%s的一边" % l, "两边一样平", "两边都往上翘"], "重的一边往下沉。")


def pulse(R):
    import cn_sci
    k = R.choice(["after", "count", "rest", "breath"])
    if k == "after":
        act = R.choice(["跑步", "跳绳", "踢球", "爬楼梯", "做操"])
        return cn_sci.it("%s以后，心跳和呼吸会怎样？" % act, "都变快", ["都变慢", "心跳停止", "没有变化"], "运动时身体需要更多氧气，心跳和呼吸都会变快。")
    if k == "count":
        sec, mul = R.choice([(15, 4), (30, 2), (10, 6)])
        n = R.choice({15: [18, 20, 21, 22, 23, 24, 25], 30: [38, 40, 42, 44, 45, 46], 10: [13, 14, 15, 16]}[sec])
        who = R.choice(["小华", "小明", "小红", "小丽"])
        return cn_sci.it("%s %d 秒内数到自己心跳 %d 次，1 分钟大约跳多少次？" % (who, sec, n), "%d 次" % (n * mul), ["%d 次" % n, "%d 次" % (n + 60), "%d 次" % (n * mul + 10)],
                         "1 分钟有 %d 个 %d 秒，%d × %d = %d。" % (mul, sec, n, mul, n * mul))
    if k == "rest":
        where = R.choice(["手腕", "脖子的侧面"])
        return cn_sci.it("用手指按在%s上，感觉到一跳一跳的，这是什么？" % where, "脉搏", ["呼吸", "打嗝", "肌肉抽筋"], "脉搏是心脏跳动时血管的跳动。")
    b = R.choice([16, 18, 20, 22])
    return cn_sci.it("安静时小明 1 分钟呼吸 %d 次，跑步后呼吸次数会怎样？" % b, "比 %d 次多" % b, ["比 %d 次少" % b, "正好 %d 次" % b, "变成 0 次" ], "运动后呼吸会变快。")
