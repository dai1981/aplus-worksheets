def f_heat(R):
    k = R.choice(["Q", "dt", "c", "mix"])
    if k == "Q":
        m, c, dt = R.choice([100, 200, 250, 500]), R.choice([(1, "물"), (0.2, "알루미늄"), (0.5, "식용유"), (0.1, "철")]), R.choice([10, 20, 30, 40])
        Q = c[0] * m * dt
        return nq("%s %d g의 온도를 %d °C 높이는 데 필요한 열량은 몇 kcal일까요? (%s의 비열: %s kcal/(kg·°C))" % (c[1], m, dt, c[1], num(c[0])), Q / 1000,
                  [c[0] * m * dt, m * dt / 1000, Q / 100, c[0] * dt], "kcal", "열량 = 비열 × 질량 × 온도 변화 = %s × %s × %d = %s kcal입니다." % (num(c[0]), num(m / 1000), dt, num(Q / 1000)))
    if k == "dt":
        m, Q = R.choice([(0.5, 10), (1, 20), (2, 30), (0.2, 4), (0.5, 15), (1, 40)])
        dt = Q / m
        return nq("물 %s kg에 %d kcal의 열을 가했습니다. 물의 온도는 몇 °C 올라갈까요? (물의 비열: 1 kcal/(kg·°C))" % (num(m), Q), dt, [Q * m, Q, dt / 2, dt + 10], "°C",
                  "온도 변화 = 열량 ÷ (비열 × 질량) = %d ÷ (1 × %s) = %s °C입니다." % (Q, num(m), num(dt)))
    if k == "c":
        m, Q, dt = R.choice([(1, 2, 10), (2, 8, 20), (1, 4.5, 10), (0.5, 1, 20), (2, 4, 10), (1, 3, 20)])
        c = Q / (m * dt)
        return nq("어떤 물질 %s kg의 온도를 %d °C 높이는 데 %s kcal가 필요했습니다. 이 물질의 비열은 몇 kcal/(kg·°C)일까요?" % (num(m), dt, num(Q)), c,
                  [Q * m * dt, Q / m, Q / dt, c * 10], "kcal/(kg·°C)", "비열 = 열량 ÷ (질량 × 온도 변화) = %s ÷ (%s × %d) = %s입니다." % (num(Q), num(m), dt, num(c)))
    t1, t2 = R.choice([(80, 20), (90, 30), (70, 10), (60, 20), (100, 40), (80, 40)])
    m1, m2 = R.choice([(1, 1), (1, 3), (3, 1), (1, 2), (2, 1)])
    T = (m1 * t1 + m2 * t2) / (m1 + m2)
    return nq("%d °C의 물 %d kg과 %d °C의 물 %d kg을 섞었습니다. 열평형이 되었을 때의 온도는 몇 °C일까요? (열은 밖으로 빠져나가지 않습니다.)" % (t1, m1, t2, m2), T,
              [(t1 + t2) / 2, t1 - t2, t1 + t2, max(t1, t2)], "°C", "뜨거운 물이 잃은 열 = 차가운 물이 얻은 열이므로 (%d × %d + %d × %d) ÷ %d = %s °C입니다." % (m1, t1, m2, t2, m1 + m2, num(T)))


def f_force(R):
    k = R.choice(["w", "moon", "spring", "net", "fric"])
    if k == "w":
        m = R.choice([1, 2, 5, 10, 20, 50, 0.5, 3])
        return nq("질량이 %s kg인 물체의 지구에서의 무게는 몇 N일까요? (질량 1 kg인 물체의 무게는 9.8 N입니다.)" % num(m), 9.8 * m, [m, m / 9.8, 9.8 + m, 9.8 * m / 6], "N", "무게 = 9.8 × 질량 = 9.8 × %s = %s N입니다." % (num(m), num(9.8 * m)))
    if k == "moon":
        w = R.choice([60, 120, 300, 600, 90, 180])
        return nq("지구에서 무게가 %d N인 물체를 달에 가져가면 무게는 몇 N일까요? (달의 중력은 지구의 약 1/6입니다.)" % w, w / 6, [w, w * 6, w / 9.8, w - 6], "N", "달에서의 무게 = %d ÷ 6 = %s N이고, 질량은 변하지 않습니다." % (w, num(w / 6)))
    if k == "spring":
        f1, x1 = R.choice([(2, 4), (5, 2), (1, 3), (4, 2), (3, 6)])
        f2 = R.choice([f1 * 2, f1 * 3, f1 * 4])
        x2 = x1 * f2 / f1
        return nq("어떤 용수철에 %d N의 추를 매달았더니 %d cm 늘어났습니다. 같은 용수철에 %d N의 추를 매달면 몇 cm 늘어날까요?" % (f1, x1, f2), x2, [x1 + f2 - f1, x1 * f2, f2, x2 / 2], "cm",
                  "용수철이 늘어난 길이는 매단 무게에 비례하므로 %d × %d ÷ %d = %s cm입니다." % (x1, f2, f1, num(x2)))
    if k == "net":
        a, b = R.choice([(10, 4), (8, 3), (20, 5), (15, 6), (12, 12), (30, 10)])
        same = R.random() < 0.5
        if same:
            return nq("한 물체에 오른쪽으로 %d N과 %d N의 힘이 함께 작용합니다. 알짜힘의 크기는 몇 N일까요?" % (a, b), a + b, [a - b, a * b, (a + b) / 2], "N", "같은 방향의 두 힘은 더합니다. %d + %d = %d N입니다." % (a, b, a + b))
        return nq("한 물체에 오른쪽으로 %d N, 왼쪽으로 %d N의 힘이 작용합니다. 알짜힘의 크기는 몇 N일까요?" % (a, b), a - b, [a + b, a * b, b, a], "N", "반대 방향의 두 힘은 큰 힘에서 작은 힘을 뺍니다. %d − %d = %d N입니다." % (a, b, a - b))
    p = R.choice([5, 10, 20, 30])
    return nq("책상 위의 상자를 %d N의 힘으로 밀었지만 상자가 움직이지 않았습니다. 이때 상자에 작용하는 마찰력은 몇 N일까요?" % p, p, [0, p * 2, p / 2, p + 10], "N", "정지해 있으므로 미는 힘과 마찰력이 평형을 이룹니다. 마찰력은 %d N입니다." % p)


def f_gas(R):
    k = R.choice(["boyle", "charles"])
    if k == "boyle":
        p1, v1 = R.choice([(1, 60), (1, 40), (2, 30), (1, 120), (3, 20), (2, 60)])
        p2 = R.choice([2, 3, 4, 6]) if p1 == 1 else R.choice([1, p1 * 2])
        v2 = p1 * v1 / p2
        return nq("온도가 일정할 때 %d기압에서 부피가 %d mL인 기체에 압력을 %d기압으로 바꾸면 부피는 몇 mL가 될까요?" % (p1, v1, p2), v2, [v1 * p2 / p1, v1, v1 - p2, v2 * 2], "mL",
                  "보일 법칙: 압력 × 부피는 일정합니다. %d × %d ÷ %d = %s mL입니다." % (p1, v1, p2, num(v2)))
    v0 = R.choice([273, 546, 819])
    t = R.choice([10, 20, 27, 50, 100])
    v = v0 + v0 * t / 273
    return nq("압력이 일정할 때 0 °C에서 부피가 %d mL인 기체를 %d °C로 가열하면 부피는 약 몇 mL가 될까요? (온도가 1 °C 올라갈 때마다 0 °C 부피의 1/273씩 늘어납니다.)" % (v0, t), v,
              [v0 + t, v0 * t / 273, v0, v0 * 2], "mL", "늘어난 부피 = %d × %d ÷ 273 = %s mL, 부피 = %s mL입니다." % (v0, t, num(v0 * t / 273), num(v)))


