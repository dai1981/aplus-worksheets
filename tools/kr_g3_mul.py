def no_carry_mul(a, d):
    """올림을 무시：各位 × d の一の位だけ"""
    s, p = 0, 1
    while a:
        s += (a % 10 * d % 10) * p
        a //= 10; p *= 10
    return s


def carry_times(a, d):
    """올림한 수에도 d を掛けてしまう誤り"""
    s, c, p = 0, 0, 1
    while a:
        v = a % 10 * d + c * d
        s += v % 10 * p
        c = v // 10
        a //= 10; p *= 10
    return s + c * p


def carries(a, d):
    c = n = 0
    while a:
        v = a % 10 * d + c
        c = v // 10
        n += 1 if c else 0
        a //= 10
    return n


def mk_mul(lo, hi, need=None, dlo=2, dhi=9):
    def mk():
        a, d = R.randint(lo, hi), R.randint(dlo, dhi)
        c = carries(a, d)
        if need is not None and (c != need if need >= 0 else c < 1):
            return None
        p = a * d
        w = [no_carry_mul(a, d), carry_times(a, d), p + 10, p - 10, p + 100, p - 100]
        return mcq("%d × %d =" % (a, d), num(p), [num(x) for x in w if x != p and x > 0],
                   "일의 자리부터 곱하고, 올림한 수는 윗자리의 곱에 <b>더해요</b>. %d × %d = <b>%s</b>" % (a, d, num(p)))
    return mk


def tens(kind):
    def mk():
        if kind == "t1":           # (몇십) × (몇)
            a, d = R.randint(1, 9) * 10, R.randint(2, 9)
        elif kind == "h1":         # (몇백) × (몇)
            a, d = R.randint(1, 9) * 100, R.randint(2, 9)
        elif kind == "tt":         # (몇십) × (몇십)
            a, d = R.randint(2, 9) * 10, R.randint(2, 9) * 10
        else:                      # (몇십몇) × (몇십)
            a, d = R.randint(11, 99), R.randint(2, 9) * 10
        p = a * d
        zeros = (str(a) + str(d)).count("0") - (str(a).rstrip("0") + str(d).rstrip("0")).count("0")
        w = [p // 10, p * 10, p + (10 ** zeros), p - (10 ** zeros)]
        base = int(str(a).rstrip("0") or "0") * int(str(d).rstrip("0") or "0")
        return mcq("%d × %d =" % (a, d), num(p), [num(x) for x in w if x != p and x > 0],
                   "%d × %d = %d를 계산하고, 곱하는 두 수의 끝에 있는 0의 개수(%d개)만큼 0을 붙여요. <b>%s</b>" % (int(str(a).rstrip("0")), int(str(d).rstrip("0")), base, zeros, num(p)))
    return mk


def tt(need_carry=True):
    """(두 자리) × (두 자리)：誤答は「(a × 일의 자리) + (a × 십의 자리) を 자리 맞추지 않고 더한다」"""
    def mk():
        a, b = R.randint(12, 98), R.randint(12, 49)
        if b % 10 == 0 or a % 10 == 0:
            return None
        p = a * b
        bt, bo = b // 10, b % 10
        w = [a * bo + a * bt, p + 10, p - 100, a * bo + a * bt * 100 if a * bt * 100 + a * bo != p else p + 1000, no_carry_mul(a, bo) + no_carry_mul(a, bt) * 10]
        return mcq("%d × %d =" % (a, b), num(p), [num(x) for x in w if x != p and x > 0],
                   "%d × %d = %d, %d × %d = %d예요. 둘을 더하면 %d + %d = <b>%s</b>" % (a, bo, a * bo, a, bt * 10, a * bt * 10, a * bo, a * bt * 10, num(p)))
    return mk


def one_by_two():
    a, b = R.randint(2, 9), R.randint(12, 99)
    if b % 10 == 0:
        return None
    p = a * b
    return mcq("%d × %d =" % (a, b), num(p), [num(x) for x in (a * (b // 10) * 10 + a + b % 10, p + 10, p - 10, no_carry_mul(b, a)) if x != p and x > 0],
               "곱하는 순서를 바꾸어도 곱은 같아요. %d × %d = %d × %d = <b>%s</b>" % (a, b, b, a, num(p)))


def compare(lo, hi, dlo, dhi):
    def mk():
        a, d = R.randint(lo, hi), R.randint(dlo, dhi)
        b, e = R.randint(lo, hi), R.randint(dlo, dhi)
        p, q = a * d, b * e
        if p == q or abs(p - q) > p // 3:
            return None
        ans = "%d × %d" % (a, d) if p > q else "%d × %d" % (b, e)
        return mcq("곱이 더 큰 것은? %d × %d, %d × %d" % (a, d, b, e), ans,
                   ["%d × %d" % (b, e) if p > q else "%d × %d" % (a, d), "두 곱이 같아요", "알 수 없어요"],
                   "%d × %d = %s, %d × %d = %s이니까 <b>%s</b> 쪽이 더 커요." % (a, d, num(p), b, e, num(q), ans))
    return mk


def missing(lo, hi, dlo, dhi):
    def mk():
        a, d = R.randint(lo, hi), R.randint(dlo, dhi)
        p = a * d
        return mcq("%d × □ = %s에서 □에 알맞은 수는?" % (a, num(p)), str(d), [str(x) for x in (d + 1, d - 1, p - a, d * 10) if x != d and x > 0],
                   "%d에 얼마를 곱해야 %s가 되는지 찾아요. %d × %d = %s → <b>%d</b>" % (a, num(p), a, d, num(p), d))
    return mk


