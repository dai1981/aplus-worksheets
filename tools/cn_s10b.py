    if k == "test":
        g, a = R.choice([("AA", "全部为显性"), ("Aa", "显性∶隐性 = 1∶1")])
        return it("对一个显性个体进行测交，后代 %s，这个个体的基因型是什么？" % a, g, ["aa", "AA 或 Aa", "AA" if g == "Aa" else "Aa"], "测交是与隐性纯合子杂交，后代表型反映待测个体的配子种类。")
    if k == "two":
        q, a, w = R.choice([("AaBb × AaBb 的后代中表型有几种", "4 种", ["9 种", "3 种", "16 种"]), ("AaBb × AaBb 的后代中基因型有几种", "9 种", ["4 种", "16 种", "3 种"]),
                            ("AaBb × AaBb 的后代中双隐性个体占多少", "1/16", ["1/4", "9/16", "3/16"]), ("AaBb × AaBb 的后代中双显性个体占多少", "9/16", ["3/16", "1/16", "1/4"]),
                            ("AaBb 能产生几种配子", "4 种", ["2 种", "8 种", "1 种"]), ("AaBb × aabb 的后代表型比例是多少", "1∶1∶1∶1", ["9∶3∶3∶1", "3∶1", "1∶2∶1"]),
                            ("AaBb × AaBb 的后代中 AABB 占多少", "1/16", ["1/4", "9/16", "1/8"]), ("AaBb × AaBb 的后代中与亲本表型不同的个体占多少", "7/16", ["9/16", "3/16", "1/16"])])
        return it("两对基因独立遗传、都是完全显性，%s？" % q, a, w, "两对相对性状的杂交可以拆成两个分离定律分别计算再相乘。")
    if k == "dom":
        p = R.choice([25, 50, 75])
        return it("一对夫妇都是某常染色体隐性遗传病的携带者（Aa），他们生一个患病孩子的概率是多少？", "1/4", ["1/2", "3/4", "1/8"], "Aa × Aa 后代 aa 占 1/4。") if p == 25 else \
            it("一对夫妇都是某常染色体隐性遗传病的携带者（Aa），他们生一个表型正常的孩子中，是携带者的概率是多少？", "2/3", ["1/2", "1/4", "3/4"], "正常孩子中 AA∶Aa = 1∶2。") if p == 50 else \
            it("母亲是红绿色盲携带者（XᴮXᵇ），父亲正常（XᴮY），他们的儿子患色盲的概率是多少？", "1/2", ["1/4", "0", "1"], "儿子的 X 染色体来自母亲，Xᵇ 的概率是 1/2。")
    if k == "dna":
        a = R.choice([10, 15, 20, 25, 30, 35, 40])
        return nq("某双链 DNA 分子中腺嘌呤（A）占碱基总数的 %d%%，鸟嘌呤（G）占多少？" % a, 50 - a, [a, 100 - a, 100 - 2 * a], "%", "A = T，G = C，A + G = 50%%，G = %d%%。" % (50 - a))
    if k == "rep":
        n = R.choice([2, 3, 4, 5])
        return nq("一个 DNA 分子复制 %d 次，得到多少个 DNA 分子？" % n, 2 ** n, [2 * n, n + 1, 2 ** (n - 1)], "", "每复制一次数量加倍：2^%d = %d 个。" % (n, 2 ** n))
    n = R.choice([100, 150, 200, 300])
    return nq("某蛋白质由 %d 个氨基酸组成，控制它合成的基因中至少有多少个碱基？（不考虑终止密码子）" % n, n * 6, [n * 3, n, n * 2], "", "1 个氨基酸 ↔ mRNA 上 3 个碱基 ↔ 基因中 6 个碱基。")


