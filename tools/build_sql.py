# -*- coding: utf-8 -*-
"""
content/  ->  sql/seed.sql   (import into MySQL with phpMyAdmin)

  python tools/build_sql.py                 # all content
  python tools/build_sql.py us/math/grade-3 # only one folder

Every row uses REPLACE INTO, so re-importing simply overwrites.
The output works in MySQL and SQLite (no backslashes allowed in content).
"""
import glob, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
CONTENT = os.path.join(ROOT, "content")
OUT = os.path.join(ROOT, "sql", "seed.sql")


def q(v):
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    if "\\" in s:
        raise SystemExit("Backslash found (use single quotes in HTML): " + s[:120])
    return "'" + s.replace("'", "''") + "'"


def row(table, d):
    cols = ", ".join(d.keys())
    vals = ", ".join(q(v) for v in d.values())
    return "REPLACE INTO %s (%s) VALUES (%s);" % (table, cols, vals)


def jdump(v):
    return json.dumps(v, ensure_ascii=False, separators=(",", ":"))


def main():
    only = sys.argv[1] if len(sys.argv) > 1 else ""
    out = ["-- generated by tools/build_sql.py", "SET NAMES utf8mb4;"]

    with open(os.path.join(CONTENT, "catalog.json"), encoding="utf-8") as f:
        cat = json.load(f)
    for c in cat["countries"]:
        out.append(row("ws_country", c))
    for s in cat["subjects"]:
        out.append(row("ws_subject", s))
    for g in cat["grades"]:
        out.append(row("ws_grade", g))

    files = sorted(glob.glob(os.path.join(CONTENT, only, "**", "*.json"), recursive=True))
    n = 0
    for path in files:
        if os.path.basename(path) == "catalog.json":
            continue
        with open(path, encoding="utf-8") as f:
            u = json.load(f)
        for s in u["sets"]:
            for it in s["items"]:
                assert len(it["c"]) == 4 and 0 <= it["a"] < 4, (path, it["q"])
        out.append(row("ws_unit", {
            "country": u["country"], "subject": u["subject"], "grade": u["grade"],
            "slug": u["slug"], "title": u["title"], "seo_title": u.get("seo_title", ""),
            "short_title": u.get("short_title", ""), "domain": u.get("domain", ""),
            "standard_code": u.get("standard_code", ""), "standard_url": u.get("standard_url", ""),
            "standard_text": u.get("standard_text", ""), "meta_desc": u.get("meta_desc", ""),
            "key_big": u.get("key_big", ""), "key_sub": u.get("key_sub", ""),
            "body_html": u.get("body_html", ""), "faq_json": jdump(u.get("faq", [])),
            "sets_json": jdump(u["sets"]), "pdf_url": u.get("pdf_url", ""),
            "sort": u.get("sort", 0), "updated": u.get("updated"),
        }))
        n += 1

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("units: %d  ->  %s (%d KB)" % (n, OUT, os.path.getsize(OUT) // 1024))


if __name__ == "__main__":
    main()
